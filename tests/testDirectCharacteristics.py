'''

Tests for the forward characteristics problem: a net marched against a wall that was given.

The module names its own settling check and this file is it. A truncated ideal contour's wall is a
streamline of a shock-free field, so marching the forward solver over that wall is solving the same
problem the inverse solve already solved, and the inverse solve is verified in
docs/NozzleContourValidation.md. It is a manufactured solution generated by a solver that has
already been checked, and it needs no external reference.

That matters because the forward march is what every family except the truncated ideal contour
relies on for its interior, and until this file existed nothing exercised it. The defect that
prompted these tests was invisible for exactly that reason: it fires on the walls the optimized
families draw and not on the one family whose interior comes from the inverse solve, so the shipped
example never saw it.

'''
import json
import os

import numpy as np
import pytest

from NOVA.characteristics import CharacteristicGas
from NOVA.directCharacteristics import marchPrescribedWall
from NOVA.wallGeometry import PrescribedWall, SampledSegment, raoThroatArc

#--------------------------------------------------------------------------------------------------------------------------#
# -- A truncated ideal contour to march over -- #
#--------------------------------------------------------------------------------------------------------------------------#

@pytest.fixture(scope = 'module')
def truncatedIdeal():

    '''One solved truncated ideal contour, without a jacket, reused by every test here.'''

    from NOVA.Nozzle import Nozzle

    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    assetPath = os.path.join(root, 'src', 'NOVA', 'assets', 'NOVANozzle.json')
    with open(assetPath, encoding = 'utf-8') as handle:
        config = json.load(handle)
    config.update({'divergingSectionType': 'tic', 'Lstar': None, 'plumeAmbientPressure': None,
                   'plotsEnabled': False, 'export': False, 'makeCoolingChannels': 'off',
                   'makeInletVolute': 'off', 'makeOutletVolute': 'off',
                   'makeRadiativeExtension': 'off', 'filmCooling': 'off'})

    scratch = os.path.join(root, 'runs', 'testDirectCharacteristics')
    os.makedirs(scratch, exist_ok = True)
    configPath = os.path.join(scratch, 'directTestConfig.json')
    with open(configPath, 'w', encoding = 'utf-8') as handle:
        json.dump(config, handle, indent = 2)

    # Redirecting the output root keeps a solve from writing into the repository. It is a change
    # to the class rather than to an instance, so it is restored whatever happens.
    originalOutputRoot = Nozzle._getOutputRoot
    try:
        Nozzle._getOutputRoot = lambda self, _base = scratch: _base
        nozzle = Nozzle()
        nozzle.generateNozzle(configPath = configPath)
    finally:
        Nozzle._getOutputRoot = originalOutputRoot

    return nozzle

def wallAndStartingLine(nozzle):

    '''

    The contour's own wall as a `PrescribedWall`, and the kernel boundary the march starts from.

    The wall is rebuilt in the two segments the march expects, the throat arc it was launched from
    and the contoured run behind it, so stations on it are comparable with the starting station.
    The starting line is the same slice of the expansion kernel the optimized families take.

    '''

    arcEnd = float(nozzle.throatWallX[-1])
    xWall = np.asarray(nozzle.xNozzleWallDivergingNonDimensional, dtype = float)
    rWall = np.asarray(nozzle.rNozzleWallDivergingNonDimensional, dtype = float)

    beyond = xWall > arcEnd + 1e-9
    contourX = np.concatenate([[arcEnd], xWall[beyond]])
    contourR = np.concatenate([[float(nozzle.throatWallR[-1])], rWall[beyond]])
    advancing = np.concatenate([[True], np.diff(contourX) > 1e-12])

    wall = PrescribedWall([raoThroatArc(nozzle.throatRadiusNonDimensional,
                                        nozzle.throatOutletCurvatureNonDimensional,
                                        float(nozzle.throatEndAngle)),
                           SampledSegment(contourX[advancing], contourR[advancing])])

    startSlice = slice(int(nozzle.numCharacteristics) - 1, None)
    blocks = (nozzle.allMachNumbers[1], nozzle.allFlowAngles[1],
              nozzle.allXPoints[1], nozzle.allRPoints[1])
    startingLine = tuple(np.asarray(block, dtype = float)[startSlice, -1] for block in blocks)
    usable = np.isfinite(startingLine[0]) & (startingLine[0] > 1.0)

    return wall, tuple(array[usable] for array in startingLine), xWall

@pytest.fixture(scope = 'module')
def marchOverTheIdealWall(truncatedIdeal):
    '''The forward march run over the inverse solve's own converged wall.'''
    gas = CharacteristicGas(truncatedIdeal.chamberGamma, truncatedIdeal.chamberRGasConstant,
                            truncatedIdeal.chamberStagnationTemperature)
    wall, startingLine, xWall = wallAndStartingLine(truncatedIdeal)

    return marchPrescribedWall(gas, wall, startingLine), xWall

