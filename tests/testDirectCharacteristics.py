def testTheMarchReachesTheExitOnAnIdealWall(marchOverTheIdealWall):
    '''
    A truncated ideal wall carries no compression to coalesce, so the march has nothing to stop it
    short. Terminating on anything but the exit means it failed to solve a case it must solve.
    '''
    march, _ = marchOverTheIdealWall
    assert march['terminated'] == 'exit'

def testTheForwardMarchReproducesTheInverseSolveItShouldAgreeWith(marchOverTheIdealWall,
                                                                  truncatedIdeal):
    '''
    The check the module is settled by. Both solvers are answering the same question on the same
    wall in the same gas, so the near-wall Mach numbers have to agree to the discretization and
    nothing more. Measured at 0.0097 worst and 0.0022 rms when this was written.
    '''
    march, xWall = marchOverTheIdealWall
    marchedX = np.asarray(march['wallX'], dtype = float)
    marchedMach = np.asarray(march['wallMach'], dtype = float)

    # The contour solution's own diverging near-wall Mach. The attribute of the same name on the
    # nozzle is the full contour including the converging section, on a different abscissa.
    inverseWallMach = np.asarray(truncatedIdeal.nozzleContourSolution.nozzleNearWallMachNumber,
                                 dtype = float)
    inside = marchedX <= xWall.max()
    difference = marchedMach[inside] - np.interp(marchedX[inside], xWall, inverseWallMach)

    assert inside.sum() > 20
    assert np.abs(difference).max() < 0.02
    assert np.sqrt(np.mean(difference**2)) < 0.005

def testTheInteriorCarriesNothingFasterThanTheExit(marchOverTheIdealWall, truncatedIdeal):
    '''
    A truncated ideal contour is designed to straighten its exit, so the exit plane is close to
    uniform and no node inside it should be running meaningfully faster than the design Mach
    number. This does not hold for the optimized families, whose exit planes are non-uniform by
    construction, which is why it is asserted here and not of them.
    '''
    march, _ = marchOverTheIdealWall
    mesh = np.asarray(march['mach'], dtype = float)
    finite = np.isfinite(mesh)

    assert finite.sum() > 1000
    assert mesh[finite].max() < truncatedIdeal.exitMachNumber * 1.02

def testACleanWallFoldsNowhere(marchOverTheIdealWall):
    '''
    A fold is two characteristics of the same family crossing, which a truncated ideal contour
    cannot produce: its wall is a streamline of a shock-free field. Counting zero of them here is
    what makes a non-zero count on another wall meaningful rather than noise.
    '''
    march, _ = marchOverTheIdealWall
    assert march['foldedLines'] == 0

def testAFoldedStepIsRejectedRatherThanKept(marchOverTheIdealWall):
    '''
    The guard the fold count reports on. Marching along a line runs downstream and inward, so a
    point that lands upstream and further out has folded back on itself. Such a point returns
    finite, supersonic and at positive radius, so none of the other guards see it, and before this
    one existed a thrust-optimized contour kept one at Mach 7.53 and minus forty degrees.

    Asserted as a property of what survives: every step along every solved line advances.
    '''
    march, _ = marchOverTheIdealWall
    x = np.asarray(march['x'], dtype = float)
    r = np.asarray(march['r'], dtype = float)

    for line in range(x.shape[1]):
        finite = np.isfinite(x[:, line]) & np.isfinite(r[:, line])
        if finite.sum() < 3:
            continue
        axial, radial = x[finite, line], r[finite, line]
        regressed = (np.diff(axial) <= 0.0) & (np.diff(radial) >= 0.0)
        assert not regressed.any(), f'line {line} kept a step that folded back on itself'
