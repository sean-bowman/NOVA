class TestDiffusionLimitedAgainstTheEquilibriumTable:

    '''

    The closed-form char removal rate against an independently generated equilibrium solution.

    The packaged table was produced by the Ablation Workshop with TARGET on the CEA thermodynamic
    database, for air, over a 25 species mixture, with equal diffusion coefficients and
    equilibrium imposed at the wall. Nothing in NOVA had a hand in it.

    At low temperature the equilibrium product of carbon and oxygen is carbon dioxide, so each
    carbon consumed takes two oxygens and the rate is half the monoxide value. Above roughly
    1200 K it is carbon monoxide, and the rate sits on a plateau until sublimation takes over
    around 3200 K. Those two plateaux are what the closed form describes, and they are where it
    can be checked.

    '''

    def table(self):

        '''The packaged TACOT table for air.'''

        return BPrimeTable.fromPackagedTable('tacotBPrimeAir')

    def testTheCarbonMonoxideBranchMatchesThePlateau(self):

        table = self.table()

        # One atmosphere, no pyrolysis gas, averaged over 1500 to 2500 K where the table is flat.
        temperatures = np.arange(1500.0, 2501.0, 25.0)
        tabulated = np.mean([table.charBPrime(101325.0, 0.0, t) for t in temperatures])
        closedForm = diffusionLimitedCharBPrime(AIRELEMENTS, product = 'CO')

        error = abs(closedForm - tabulated) / tabulated
        assert error < 5.0e-5, (closedForm, tabulated, error)

    def testTheCarbonDioxideBranchMatchesTheLowTemperatureLimit(self):

        table = self.table()

        tabulated = table.charBPrime(101325.0, 0.0, 250.0)
        closedForm = diffusionLimitedCharBPrime(AIRELEMENTS, product = 'CO2')

        error = abs(closedForm - tabulated) / tabulated
        assert error < 5.0e-5, (closedForm, tabulated, error)

    def testTheDioxideBranchIsExactlyHalfTheMonoxideBranch(self):

        monoxide = diffusionLimitedCharBPrime(AIRELEMENTS, product = 'CO')
        dioxide = diffusionLimitedCharBPrime(AIRELEMENTS, product = 'CO2')

        assert abs(dioxide - 0.5 * monoxide) < 1.0e-15

    def testTheLowTemperatureLimitIsIndependentOfPressure(self):

        table = self.table()

        values = [table.charBPrime(pressure, 0.0, 250.0)
                  for pressure in (101.325, 1013.25, 10132.5, 101325.0)]

        # An elemental transport limit does not know about pressure, and the table agrees.
        assert max(values) - min(values) < 1.0e-9

    def testTheClosedFormSatisfiesItsOwnElementalBalance(self):

        # Given B'c, the wall mass fractions follow, and the carbon-to-oxygen ratio at the wall
        # has to be the one carbon monoxide fixes. This is the identity the derivation rests on.
        edge = propellantElementMassFractions({'C': 0.8594, 'H': 0.1406}, {'O': 1.0}, 2.7)
        gas = elementMassFractionsFromMoles({'C': 0.206, 'H': 0.679, 'O': 0.115})
        gasBPrime = 0.3

        charBPrime = diffusionLimitedCharBPrime(edge, gasBPrime, gas, 'CO')

        total = 1.0 + charBPrime + gasBPrime
        wallCarbon = (edge['C'] + charBPrime + gasBPrime * gas['C']) / total
        wallOxygen = (edge['O'] + gasBPrime * gas['O']) / total

