class TestDecompositionKinetics:

    '''

    The closed-form step against the rate law it is supposed to integrate.

    A reaction order other than one separates and integrates exactly, which removes the stiffness
    of the decomposition entirely and lets the timestep be set by conduction alone. That is worth
    having only if the closed form is actually the integral of the rate, so it is checked against
    a finely substepped explicit integration of the rate itself.

    '''

    def material(self):

        '''TACOT, whose two decomposing phases both carry a reaction order of three.'''

        return CharringMaterial.fromStore('TACOT v3.0')

    @pytest.mark.parametrize('temperature', [700.0, 900.0, 1200.0])
    def testTheClosedFormStepIntegratesTheRateLaw(self, temperature):

        material = self.material()
        start = material.componentVirginDensity.copy()

        closedForm = material.advanceDecomposition(start[None, :], np.array([temperature]), 2.0)[0]

        stepped = start[None, :].copy()
        substeps = 20000
        for _ in range(substeps):
            rate = material.decompositionRate(stepped, np.array([temperature]))
            stepped = stepped - rate * (2.0 / substeps)

        for exact, marched in zip(closedForm, stepped[0]):
            if exact > 1.0e-6:
                assert abs(marched - exact) / exact < 1.0e-3, (temperature, exact, marched)

    def testDecompositionNeverOvershootsTheCharDensity(self):

        material = self.material()
        start = material.componentVirginDensity.copy()

        # An hour at 3000 K is far past anything a liner sees.
        finished = material.advanceDecomposition(start[None, :], np.array([3000.0]), 3600.0)[0]

        assert np.all(finished >= material.componentCharDensity - 1.0e-12)
        assert np.all(finished <= start + 1.0e-12)

    def testAThirdOrderReactionApproachesCompletionWithoutReachingIt(self):

        material = self.material()
        start = material.componentVirginDensity.copy()
        decomposing = material.preExponentialFactor > 0.0

        # Both TACOT resin phases carry a reaction order of three, whose closed form decays as the
        # inverse square root of time. It therefore never reaches the char density exactly, and a
        # solver that returned exactly the char density would be wrong rather than converged.
        # Quadrupling the time halves what is left.
        shortRun = material.advanceDecomposition(start[None, :], np.array([3000.0]), 900.0)[0]
        longRun = material.advanceDecomposition(start[None, :], np.array([3000.0]), 3600.0)[0]

        shortRemaining = (shortRun - material.componentCharDensity)[decomposing]
        longRemaining = (longRun - material.componentCharDensity)[decomposing]

        assert np.all(longRemaining > 0.0)
        assert np.allclose(shortRemaining / longRemaining, 2.0, rtol = 1.0e-3)

        # What is left is negligible against the density it started from.
        assert np.all(longRemaining / material.componentVirginDensity[decomposing] < 1.0e-3)

    def testNothingHappensBelowTheOnsetTemperature(self):

        material = self.material()
        start = material.componentVirginDensity.copy()

        # 320 K is below the lower of the two onset temperatures, which is 333 K.
        unchanged = material.advanceDecomposition(start[None, :], np.array([320.0]), 1000.0)[0]

        assert np.allclose(unchanged, start)

    def testTheReinforcementNeverDecomposes(self):

        material = self.material()
        start = material.componentVirginDensity.copy()

        finished = material.advanceDecomposition(start[None, :], np.array([4000.0]), 3600.0)[0]

        # The carbon fiber is the component with no rate constant.
        inert = material.preExponentialFactor == 0.0
        assert np.allclose(finished[inert], start[inert])

    def testTheMixingRuleReturnsTheStoredEndStateDensities(self):

        material = self.material()

        virgin = material.bulkDensity(material.componentVirginDensity)
        char = material.bulkDensity(material.componentCharDensity)

        assert abs(virgin - material.virginDensity) < 1.0e-9
        assert abs(char - material.charDensity) < 1.0e-9

