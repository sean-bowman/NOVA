# -- NOVA: Ablative Material Response Tests -- #

'''

Verification and validation of the charring ablator model in NOVA.ablative.

The two words are kept apart on purpose. Verification asks whether the discretisation solves the
equations it claims to, and is answered against solutions that are known in closed form, so the
error is exact and quantified. Validation asks whether those equations describe reality, and is
answered against data somebody else produced.

Verification here covers the semi-infinite conduction solutions with both kinds of surface
condition, the steady ablation profile, the closed-form decomposition, mesh and timestep
convergence, and the discrete energy balance.

Validation rests on two independent things. The closed-form diffusion-limited char removal rate is
set against the TACOT equilibrium B-prime table, which was generated by the Ablation Workshop with
CEA data and a 25 species mixture; the two agree to better than 0.005 per cent in the asymptotic
limits the closed form describes. And the full material response is set against the FIAT baseline
of Ablation Workshop test case 1, read off the published figure. The digitized reference values are
recorded below, along with how accurately the figure can be read.

What is not validated is the nozzle application. The tests here show that its plumbing holds
together and that its results behave the way physics requires, which is not the same as showing
they are right.

Author: Sean Bowman

'''

