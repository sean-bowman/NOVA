class TestConductionAgainstClosedForm:

    '''

    The conduction solver against solutions that are known exactly.

    Both cases are the semi-infinite solid, which the model reproduces by making the sample deep
    enough that the back face never moves off its initial temperature. Five centimeters against a
    thermal penetration of eight millimeters is deep by a factor of six, and the erf at that
    argument is one to fourteen figures.

    '''

    conductivity = 0.5
    density = 1000.0
    specificHeat = 1000.0
    duration = 30.0
    probeDepths = np.array([0.0005, 0.001, 0.002, 0.004, 0.006, 0.008, 0.012])

    @property
    def diffusivity(self):

        '''Thermal diffusivity of the test solid [m^2/s].'''

        return self.conductivity / (self.density * self.specificHeat)

    def solve(self, environment, nodes = 161, growthRatio = 1.03, timeStep = 0.02):

        '''One run of the constant-property solid under a given surface condition.'''

        return solveMaterialResponse(
            constantPropertySolid(self.conductivity, self.density, self.specificHeat),
            environment, thickness = 0.05, duration = self.duration,
            timeStep = timeStep, numberOfNodes = nodes, growthRatio = growthRatio,
            initialTemperature = 300.0, outputInterval = self.duration)

    def testStepSurfaceTemperatureMatchesTheErrorFunction(self):

        # T(y, t) = Ts + (T0 - Ts) erf(y / 2 sqrt(alpha t)), Carslaw and Jaeger section 2.4.
        result = self.solve(AblationEnvironment(surfaceClosure = 'temperature',
                                                surfaceTemperature = 1000.0))

        argument = self.probeDepths / (2.0 * np.sqrt(self.diffusivity * self.duration))
        exact = 1000.0 + (300.0 - 1000.0) * erf(argument)
        model = np.array([result.temperatureAtDepth(depth)[-1] for depth in self.probeDepths])

        # 0.081 K on a 700 K step is 0.012 per cent. The bound is set an order above what the
        # solver delivers so that it catches a defect rather than mesh noise.
        assert np.max(np.abs(model - exact)) < 1.0, np.max(np.abs(model - exact))

    def testConstantSurfaceFluxMatchesTheClosedForm(self):

        # Ts(t) = T0 + 2 q sqrt(alpha t / pi) / k, and the profile carries the erfc term.
        surfaceFlux = 5.0e4
        result = self.solve(AblationEnvironment(
            surfaceClosure = 'diffusionLimited', transferCoefficient = 0.0,
            radiationInput = surfaceFlux, viewFactor = 0.0,
            edgeElements = {'O': 1.0}, charRemovalEfficiency = 0.0))

        rise = 2.0 * surfaceFlux * np.sqrt(self.diffusivity * self.duration / np.pi) \
               / self.conductivity
        assert abs(result.surfaceTemperature[-1] - (300.0 + rise)) < 2.0

        argument = self.probeDepths / (2.0 * np.sqrt(self.diffusivity * self.duration))
        exact = 300.0 + (2.0 * surfaceFlux / self.conductivity) * (
            np.sqrt(self.diffusivity * self.duration / np.pi) * np.exp(-argument**2)
            - 0.5 * self.probeDepths * erfc(argument))
        model = np.array([result.temperatureAtDepth(depth)[-1] for depth in self.probeDepths])

        assert np.max(np.abs(model - exact)) < 2.0, np.max(np.abs(model - exact))

    def testNoRecessionWithoutCharRemoval(self):

        result = self.solve(AblationEnvironment(
            surfaceClosure = 'diffusionLimited', transferCoefficient = 0.0,
            radiationInput = 5.0e4, viewFactor = 0.0,
            edgeElements = {'O': 1.0}, charRemovalEfficiency = 0.0))

        assert result.recession[-1] == 0.0

    def testTheEnergyBalanceClosesWhenTheSurfaceIsFixed(self):

        result = self.solve(AblationEnvironment(surfaceClosure = 'temperature',
                                                surfaceTemperature = 1000.0))

        # Nothing recedes, so every term in the balance sits on a control volume that does not
        # move and the closure is exact to the Newton tolerance.
        assert result.energyImbalance < 1.0e-8, result.energyImbalance

    @pytest.mark.parametrize('nodes, growthRatio', [(41, 1.14), (81, 1.06), (161, 1.03)])
    def testRefiningTheMeshImprovesTheAnswer(self, nodes, growthRatio):

        result = self.solve(AblationEnvironment(surfaceClosure = 'temperature',
                                                surfaceTemperature = 1000.0),
                            nodes = nodes, growthRatio = growthRatio)

        argument = self.probeDepths / (2.0 * np.sqrt(self.diffusivity * self.duration))
        exact = 1000.0 + (300.0 - 1000.0) * erf(argument)
        model = np.array([result.temperatureAtDepth(depth)[-1] for depth in self.probeDepths])
        error = np.max(np.abs(model - exact))

        # Every mesh in the range is already inside a kelvin; the point of the sweep is that none
        # of them is wildly off, which is what a broken boundary treatment would produce.
        assert error < 5.0, (nodes, error)

    def testHalvingTheTimestepDoesNotChangeAConvergedAnswer(self):

        environment = AblationEnvironment(surfaceClosure = 'temperature',
                                          surfaceTemperature = 1000.0)
        coarse = self.solve(environment, timeStep = 0.04)
        fine = self.solve(environment, timeStep = 0.01)

        probe = 0.002
        assert abs(coarse.temperatureAtDepth(probe)[-1]
                   - fine.temperatureAtDepth(probe)[-1]) < 0.5

class TestSteadyAblation:

    '''

    The moving mesh against the steady ablation solution.

    Once the recession rate is constant and the profile has stopped changing in the frame of the
    surface, the energy equation collapses to alpha T'' + s_dot T' = 0, whose solution is a pure
    exponential decaying into the material over a length alpha / s_dot. Reproducing it exercises
    the one term nothing else in this file touches: the material moving past the mesh.

    '''

    conductivity = 0.5
    density = 1000.0
    specificHeat = 1000.0

    def result(self):

        '''A long run at a fixed char blowing rate, taken to steady state.'''

        environment = AblationEnvironment(
            surfaceClosure = 'diffusionLimited',
            transferCoefficient = 0.60,
            recoveryTemperature = 3000.0,
            edgeSpecificHeat = 2000.0,
            edgeElements = {'O': 1.0},
            viewFactor = 0.0,
            ambientTemperature = 300.0)

        return solveMaterialResponse(
            constantPropertySolid(self.conductivity, self.density, self.specificHeat),
            environment, thickness = 0.08, duration = 120.0, timeStep = 0.04,
            numberOfNodes = 201, growthRatio = 1.02, initialTemperature = 300.0,
            outputInterval = 10.0)

    def testTheRecessionRateIsTheOneTheClosureAsksFor(self):

        result = self.result()

        charBPrime = diffusionLimitedCharBPrime({'O': 1.0})
        expected = 0.60 * blowingCorrection(charBPrime) * charBPrime / self.density
        observed = (result.recession[-1] - result.recession[-2]) \
                   / (result.time[-1] - result.time[-2])

        assert abs(observed - expected) / expected < 1.0e-6, (observed, expected)

    def testTheProfileIsTheSteadyAblationExponential(self):

        result = self.result()

        diffusivity = self.conductivity / (self.density * self.specificHeat)
        charBPrime = diffusionLimitedCharBPrime({'O': 1.0})
        recessionRate = 0.60 * blowingCorrection(charBPrime) * charBPrime / self.density

        depths = np.linspace(0.0, 0.012, 25)
        mesh = result.normalizedPosition * (result.initialThickness - result.recession[-1])
        model = np.interp(depths, mesh, result.temperature[-1])
        wall = result.surfaceTemperature[-1]
        exact = 300.0 + (wall - 300.0) * np.exp(-recessionRate * depths / diffusivity)

        # 14 K on a 1970 K wall-to-far-field difference is 0.71 per cent, and it is the first
        # order error of the upwinded mesh-motion term.
        assert np.max(np.abs(model - exact)) / (wall - 300.0) < 0.015

    def testTheSteadyWallTemperatureBalancesConvectionAgainstTheMaterialItHeats(self):

        result = self.result()

        # At steady state everything conducted in goes to raising the incoming material from the
        # far field to the wall, so the balance closes on a single algebraic statement.
        charBPrime = diffusionLimitedCharBPrime({'O': 1.0})
        blown = 0.60 * blowingCorrection(charBPrime)
        charMassFlux = blown * charBPrime
        expected = (blown * 2000.0 * 3000.0 + charMassFlux * self.specificHeat * 300.0) \
                   / (blown * 2000.0 + charMassFlux * self.specificHeat)

        assert abs(result.surfaceTemperature[-1] - expected) / expected < 0.01

class TestEnergyClosureUnderRecession:

    '''

    How well the discrete energy balance closes once the surface moves, and how that improves.

    The surface node carries no volume, which is the convention that makes the surface energy
    balance an exact algebraic statement at the surface temperature. The price is that the
    material leaving through that node is not in any control volume, so the global bookkeeping
    carries a first order error in the size of the first cell. It has to be shown to be first
    order, and it has to be shown not to contaminate the answer.

    '''

    def result(self, nodes, growthRatio):

        '''Twenty seconds of the convective test case at a given mesh.'''

        environment = AblationEnvironment(
            surfaceClosure = 'bPrimeTable',
            transferCoefficient = (np.array([0.0, 0.1, 60.0]), np.array([0.0, 0.3, 0.3])),
            edgeEnthalpy = (np.array([0.0, 0.1, 60.0]), np.array([0.0, 1.5e6, 1.5e6])),
            pressure = 101325.0, ambientTemperature = 300.0, viewFactor = 1.0)

        return solveMaterialResponse(
            'TACOT v3.0', environment, thickness = 0.05, duration = 20.0, timeStep = 0.04,
            numberOfNodes = nodes, growthRatio = growthRatio, initialTemperature = 300.0,
            outputInterval = 20.0)

    def testTheClosureErrorIsFirstOrderInTheSurfaceCell(self):

        coarse = self.result(61, 1.08)
        medium = self.result(121, 1.04)
        fine = self.result(241, 1.02)

        # Each step roughly halves the first cell, so a first order error roughly halves too.
        assert 1.7 < coarse.energyImbalance / medium.energyImbalance < 2.3
        assert 1.7 < medium.energyImbalance / fine.energyImbalance < 2.3

    def testRecessionAndWallTemperatureAreConvergedAcrossThatRange(self):

        coarse = self.result(61, 1.08)
        fine = self.result(241, 1.02)

        assert abs(fine.recession[-1] - coarse.recession[-1]) / fine.recession[-1] < 0.005
        assert abs(fine.surfaceTemperature[-1] - coarse.surfaceTemperature[-1]) < 3.0

