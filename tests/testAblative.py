class TestBlowingCorrection:

    '''The correlation, its limit at no blowing, and the shape it has to have.'''

    def testItIsExactlyOneAtNoBlowing(self):

        assert blowingCorrection(0.0) == 1.0

    def testTheSeriesAndTheRatioAgreeAcrossTheSwitch(self):

        # The implementation switches to a series below an argument of 1e-6 to avoid 0/0.
        justBelow = blowingCorrection(0.9e-6 / 2.0 / 0.5)
        justAbove = blowingCorrection(1.1e-6 / 2.0 / 0.5)

        assert abs(justBelow - justAbove) < 1.0e-6

    @pytest.mark.parametrize('bPrime', [0.05, 0.2, 1.0, 3.0, 10.0])
    def testItMatchesTheCorrelationItClaims(self, bPrime):

        argument = 2.0 * 0.5 * bPrime
        assert abs(blowingCorrection(bPrime) - np.log(1.0 + argument) / argument) < 1.0e-12

    def testMoreBlowingAlwaysMeansLessTransfer(self):

        values = [blowingCorrection(b) for b in (0.0, 0.1, 0.5, 1.0, 2.0, 5.0)]

        assert all(later < earlier for earlier, later in zip(values, values[1:]))

    def testTheLaminarFactorBlocksLessThanTheTurbulentOne(self):

        assert blowingCorrection(1.0, 0.4) > blowingCorrection(1.0, 0.5)

    def testMassEnteringTheWallIsRefused(self):

        with pytest.raises(InvalidInputError):
            blowingCorrection(-0.1)

