class TestAblationWorkshopTestCaseOne:

    '''

    The full in-depth response against the FIAT baseline of the first Ablation Workshop test case.

    This is the comparison the workshop itself designated: FIAT results from the Thermal
    Performance Data Base, on a fixed surface temperature so that conduction and pyrolysis are
    isolated from the boundary layer. Fourteen codes ran it in 2011 and the workshop reported
    agreement between type 1 codes as mostly below one per cent.

    The reference values here are digitized from the published figure, so the comparison is only
    as good as that figure can be read, which is a few kelvin. The tolerances below sit at three
    per cent, and the actual agreement is better than one per cent at five of the six probes.

    '''

    @pytest.mark.parametrize('depth', sorted(FIATPROBES))
    def testEachTemperatureProbeAgreesWithFiat(self, testCaseOne, depth):

        reference = FIATPROBES[depth]
        model = testCaseOne.temperatureAtDepth(depth)[-1]

        assert abs(model - reference) / reference < 0.03, (depth, model, reference)

    def testTheNearSurfaceProbesAgreeToBetterThanOnePerCent(self, testCaseOne):

        # The deepest probe is the one the mesh resolves least well and it converges toward the
        # reference as the mesh is refined. The four shallower ones are already inside one
        # per cent at this resolution.
        for depth in (0.001, 0.002, 0.004, 0.008):
            model = testCaseOne.temperatureAtDepth(depth)[-1]
            assert abs(model - FIATPROBES[depth]) / FIATPROBES[depth] < 0.01, depth

    def testTheBackFaceStaysAtItsInitialTemperature(self, testCaseOne):

        # Fifty millimeters of a material with a conductivity near half a watt per meter kelvin
        # does not notice a minute of heating at the other end, and FIAT says the same.
        assert abs(testCaseOne.backFaceTemperature[-1] - 298.0) < 1.0

    def testThePyrolysisFrontIsWhereFiatPutsIt(self, testCaseOne):

        model = testCaseOne.pyrolysisDepth[-1]

        assert abs(model - FIATVIRGINFRONT) / FIATVIRGINFRONT < 0.04, model

    def testTheCharFrontIsWhereFiatPutsIt(self, testCaseOne):

        model = testCaseOne.charDepth[-1]

        assert abs(model - FIATCHARFRONT) / FIATCHARFRONT < 0.05, model

    def testTheCharFrontTrailsThePyrolysisFront(self, testCaseOne):

        # The material chars from the surface down, so the fully charred depth is always the
        # shallower of the two fronts.
        assert np.all(testCaseOne.charDepth <= testCaseOne.pyrolysisDepth + 1.0e-12)

    def testTheGasFluxPeaksEarlyAndDecays(self, testCaseOne):

        # The resin nearest the surface goes first and takes the rate with it. FIAT peaks within
        # a couple of seconds and is down to a fifth of the peak by a minute.
        flux = testCaseOne.pyrolysisGasMassFlux
        peak = int(np.argmax(flux))

        assert testCaseOne.time[peak] < 5.0
        assert flux[-1] < 0.3 * flux[peak]

    def testTheSurfaceHoldsTheTemperatureItWasGiven(self, testCaseOne):

        held = testCaseOne.surfaceTemperature[testCaseOne.time > 1.0]

        assert np.allclose(held, 1644.0, atol = 1.0e-6)

    def testNothingRecedes(self, testCaseOne):

        assert np.all(testCaseOne.recession == 0.0)

    def testTheEnergyBalanceClosesToMachinePrecision(self, testCaseOne):

        assert testCaseOne.energyImbalance < 1.0e-8, testCaseOne.energyImbalance

