def constantPropertySolid(conductivity = 0.5, density = 1000.0, specificHeat = 1000.0,
                          emissivity = 0.0) -> CharringMaterial:

    '''

    A solid with no decomposition and no temperature dependence.

    Every closed-form conduction solution assumes constant properties, so verifying against one
    needs a material that has them. Enthalpy is exactly specificHeat times temperature, which
    keeps the enthalpy formulation and the temperature formulation of the same problem identical.

    Parameters:
    -----------
    conductivity : float
        Thermal conductivity [W/m-K].
    density : float
        Density [kg/m^3].
    specificHeat : float
        Specific heat [J/kg-K].
    emissivity : float
        Surface emissivity [-].

    Returns:
    --------
    CharringMaterial

    '''

    grid = [200.0, 6000.0]
    state = {'specificHeat': [specificHeat, specificHeat],
             'thermalConductivity': [conductivity, conductivity],
             'enthalpy': [specificHeat * grid[0], specificHeat * grid[1]],
             'emissivity': emissivity}

    return CharringMaterial(
        name = 'constant property solid',
        virginDensity = density, charDensity = density,
        temperature = grid, virgin = state, char = state,
        components = ({'name': 'inert', 'virginDensity': density, 'charDensity': density,
                       'preExponentialFactor': 0.0, 'activationTemperature': 0.0,
                       'reactionOrder': 0.0, 'onsetTemperature': 1.0e9},),
        resinVolumeFraction = 0.0, porosity = 0.0)

def surfaceScheduleOfTestCaseOne(time: float) -> float:

    '''The surface temperature of Ablation Workshop test case 1: 298 K to 1644 K over 0.1 s.'''

    return 298.0 + (1644.0 - 298.0) * min(time / 0.1, 1.0)

