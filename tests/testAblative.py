def nozzleStations():

    '''A small converging-diverging contour and the exhaust that flows through it.'''

    gamma = 1.19
    throatRadius = 0.05
    axial = np.linspace(-0.06, 0.15, 7)
    radius = np.where(axial < 0.0,
                      throatRadius * (1.0 + 0.8 * (axial / 0.06)**2),
                      throatRadius * (1.0 + 1.4 * (np.abs(axial) / 0.15)**1.3))
    from NOVA.gasDynamics import machFromAreaRatio, staticTemperatureRatio
    mach = np.array([machFromAreaRatio(float((r / throatRadius)**2), gamma,
                                       'subsonic' if x < 0.0 else 'supersonic')
                     for r, x in zip(radius, axial)])
    staticTemperature = 3550.0 * np.array(
        [staticTemperatureRatio(float(m), gamma) for m in mach])

    return axial, radius, mach, staticTemperature, gamma

