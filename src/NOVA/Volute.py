
# -- Volute Class Definition -- #

'''

You heard the man, make da volute!

This class definition structures the generation of Volute geometry.

----------------------------------------------------------------------
                Geometry Generation Conventions
----------------------------------------------------------------------

> The coordinate axes are as follows:
    - X (i_hat) is the direction of the incoming / outgoing fluid from
      the largest volute cross section
    - Y (j_hat) is the direction orthogonal to X (i_hat) in the plane
      of the scroll of the volute
    - Z (k_hat) completes orthogonality, and is the direction orthogonal
      to the fluid flow of the volute

> To that end, when planar cross sections are drawn they are created in
the YZ plane. This geometry convention aligns with the conventions of
traditional CAD softwares such that importing volute geometry from this
generator will line up with expectations and conventions for typical
CAD softwares.

> Outer walls can also be generated by passing in either a wall
thickness, array of wall thickness, or hoop stress parameters. To size
walls by hoop stress, both the target hoop stress and pressure 
differential between the fluid volume and ambient must be passed in.
Hoop stress wall thickness calculations are done with respect to the 
hydraulic diameter by calling the utils hoop stress calculator.

> The numbers a cross section measures live in voluteSections.py: the area, perimeter and
hydraulic diameter of each family, the area law that distributes them around the wrap, and where
an anchor puts a section relative to the scroll radius. This module draws and sweeps them. The
split is there because a family described once cannot drift between the generators that draw it.

> All units are in Mass Base SI
    - Length      [m]
    - Area        [m^2]
    - Volume      [m^3]
    - Temperature [K]
    - Pressure    [Pa]
    - Stress      [Pa]
    - Mass Flow   [kg/s]

Author: Sean Bowman

'''

