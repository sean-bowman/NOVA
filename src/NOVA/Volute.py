    def generateSquarcVolute(self):

        '''
        
        get squarcked, idiot.

        This cross section is a circle squared off at the upper inner corner.
        The printability angle is defined relative to horizontal (XY plane, plane of the scroll)
        The printability angle is maintained as the radius of the arc changes.

        The area distribution can be bounded either by hydraulic diameter or CSA on
        both the interface and expanded sides, or either hydraulic diameter or CSA on one side
        and number of orifices.

        '''

        def drawCircleSupportThick(R):

            # scope inputs
            thetaCirc   = np.linspace(0, 2*np.pi, self.crossSectionResolution*4)
            yCircleWall = R*np.cos(thetaCirc)
            zCircleWall = R*np.sin(thetaCirc)
            t           = 0.00075        # printability thickness, [m]
            r           = 0.001          # printability fillet radius, [m]
            a           = np.deg2rad(30) # printability angle, [deg]->[rad]

            ## rectilinear wall
            D = 2*R # dummy extension length, to be trimmed later
            yRectilinear = np.array([ t/2, t/2])
            zRectilinear = np.array([-D,   D  ])

            #### upper transition body

            ## rectilinear overhang
            # find where circle wall violates printability
            yOverhangRadial             = np.array([0, D*np.sin(a)])
            zOverhangRadial             = np.array([0, D*np.cos(a)])
            overhangRadialIntersection  = intersection(yOverhangRadial,zOverhangRadial,yCircleWall,zCircleWall)
            yOverhangRadialIntersection = overhangRadialIntersection[0][0][0]
            zOverhangRadialIntersection = overhangRadialIntersection[1][0][0]
            # draw extended linear overhang
            yOverhang = np.array([yOverhangRadialIntersection - D*np.cos(a),yOverhangRadialIntersection + D*np.cos(a)])
            zOverhang = np.array([zOverhangRadialIntersection - D*np.sin(a),zOverhangRadialIntersection + D*np.sin(a)])

            ### fillets
            yOverhangOff, zOverhangOff = parallelOffset(yOverhang,zOverhang,-r)
            ## circle wall fillet
            yCircleWallOff, zCircleWallOff = parallelOffset(yCircleWall,zCircleWall,r)
            # draw circle
            filletCenter1  = intersection(yCircleWallOff,zCircleWallOff,yOverhangOff,zOverhangOff)
            yFilletCenter1 = filletCenter1[0][0][0]
            zFilletCenter1 = filletCenter1[1][0][0]
            yFilletCircle1 = 1.005*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + yFilletCenter1
            zFilletCircle1 = 1.005*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + zFilletCenter1
            # trim overhang
            overhangIntersections = intersection(yOverhang,zOverhang,yFilletCircle1,zFilletCircle1)
            yOverhangIntersection = overhangIntersections[0][0][0]
            zOverhangIntersection = overhangIntersections[1][0][0]
            yOverhang[-1]         = yOverhangIntersection
            zOverhang[-1]         = zOverhangIntersection
            # trim wall arc
            wallIntersections     = intersection(yCircleWall,zCircleWall,yFilletCircle1,zFilletCircle1)
            yWallIntersection1     = wallIntersections[0][-1][0]
            zWallIntersection1     = wallIntersections[1][-1][0]
            thetaWallIntersection = np.arctan((zWallIntersection1)/(yWallIntersection1))
            yArcUpper = (L) * np.cos(np.linspace(thetaWallIntersection,np.pi/2,int(self.crossSectionResolution/4)))
            zArcUpper = (L) * np.sin(np.linspace(thetaWallIntersection,np.pi/2,int(self.crossSectionResolution/4)))
            # trim fillet
            thetaWallIntersection     = np.arctan((zWallIntersection1-zFilletCenter1)/(yWallIntersection1-yFilletCenter1))
            thetaOverhangIntersection = np.arctan((zOverhangIntersection-zFilletCenter1)/(yFilletCenter1-yOverhangIntersection))
            yFillet1 = (1.005*r) * np.cos(np.linspace(thetaWallIntersection,np.pi-thetaOverhangIntersection,int(self.crossSectionResolution/4))) + yFilletCenter1
            zFillet1 = (1.005*r) * np.sin(np.linspace(thetaWallIntersection,np.pi-thetaOverhangIntersection,int(self.crossSectionResolution/4))) + zFilletCenter1
            ## rectilinear wall fillet
            yRectilinearOff, zRectilinearOff = parallelOffset(yRectilinear,zRectilinear,-r)
            # draw circle
            filletCenter2  = intersection(yRectilinearOff,zRectilinearOff,yOverhangOff,zOverhangOff)
            yFilletCenter2 = filletCenter2 [0][0][0]
            zFilletCenter2 = filletCenter2 [1][0][0]
            yFilletCircle2 = 1.005*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + yFilletCenter2
            zFilletCircle2 = 1.005*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + zFilletCenter2
            # trim overhang
            overhangIntersections = intersection(yOverhang,zOverhang,yFilletCircle2,zFilletCircle2)
            yOverhangIntersection = overhangIntersections[0][0][0]
            zOverhangIntersection = overhangIntersections[1][0][0]
            yOverhang[0] = yOverhangIntersection
            zOverhang[0] = zOverhangIntersection
            # trim rectilinear
            rectilinearIntersections = intersection(yRectilinear,zRectilinear,yFilletCircle2,zFilletCircle2)
            yRectilinearIntersection = rectilinearIntersections[0][0][0]
            zRectilinearIntersection = rectilinearIntersections[1][0][0]
            yRectilinear[-1] = yRectilinearIntersection
            zRectilinear[-1] = zRectilinearIntersection
            # trim fillet
            thetaWallIntersection     = np.arctan((zRectilinearIntersection-zFilletCenter2)/(yFilletCenter2-yRectilinearIntersection))
            thetaOverhangIntersection = np.arctan((zOverhangIntersection-zFilletCenter2 )/(yFilletCenter2 -yOverhangIntersection))
