    def generateVolute(self):

        '''
        
        The structure of the volute generator assumes that the relevant properties of the volute
        are pre-defined as a part of instantiating the Volute() class and therefore the generate
        volute method does not require any passed-in variables. It simply exists to execute the
        generation of volute geometry and assign the values in the calculated arrays to your volute
        object.
        
        '''

        import os

        # Where an exported STL is written. Reading it off the launching script's directory put
        # geometry wherever the entry point happened to live, and failed outright in a session
        # with no script behind it, so it is a property of the volute with the working directory
        # as its default.
        outputDirectory = self.outputDirectory or os.getcwd()
        os.makedirs(outputDirectory, exist_ok = True)

        # # Step 1: Make the diffuser
        # self.generateDiffuser()

        # Step 2: Determine the type of volute to create and generate it. A name the generator
        # does not build has to be refused here: returning empty arrays looks like a volute with
        # no geometry in it rather than a cross section that was never drawn.
        family = str(self.crossSectionType).lower()
        checkFamily(family)
        checkScrollType(str(self.scrollType).lower())

        # A support is a shape rather than a flag, so a name that is neither shape nor 'off' asked
        # for something that does not exist and used to draw nothing without saying so.
        support = str(self.circlePrintability).lower()
        if support not in VOLUTEPRINTABILITY:
            raise ValueError(f'circlePrintability must be one of '
                             f'{", ".join(VOLUTEPRINTABILITY)}, not {self.circlePrintability!r}.')

        if str(self.scaledBy).lower() != 'linear':
            raise ValueError("scaledBy must be 'linear'. The area law is linear in wrap angle; no "
                             'other distribution is implemented.')

        # The overhang support is drawn from a circular wall, so it has no squircle form: its
        # fillets are found by intersecting the support against a circular arc, which on a
        # squircle's straight faces has no solution.
        if family != 'circle' and str(self.circlePrintability).lower() in ('thick', 'thin'):
            raise ValueError(f'A printability support is drawn for a circular cross section only, '
                             f'not for {family!r}. Draw the section as a circle, or leave the '
                             f'support off.')

        match family:
            case 'circle':
                self.generateCircleVolute()
            case 'squarc':
                self.generateSquarcVolute()

        # Step 3: Record what the swept surface encloses, which is not what the area law asked
        # for: a section is drawn as a polygon inscribed in its own profile, and a support inside
        # the duct takes area back out of it.
        self.drawnArea = sweptSectionAreas(self.xVolute, self.yVolute, self.zVolute)
        self.flowArea = self.drawnArea - np.asarray(self.supportArea, dtype = float) \
            if np.size(self.supportArea) else self.drawnArea

        # Step 4: Export geometry (if user specified)
        if self.export == 'on':

            py2cad(os.path.join(outputDirectory, self.filename + '.stl'), self.xVolute, self.yVolute, self.zVolute)
            if self.wallThickness is not None:
                py2cad(os.path.join(outputDirectory, self.filename + '_eggShell.stl'), self.xShell, self.yShell, self.zShell)
            if self.circlePrintability.lower() == 'thick':
                py2cad(os.path.join(outputDirectory, self.filename + '_internalSupportWall.stl'),        self.xInternalSupportWall, self.yInternalSupportWall, self.zInternalSupportWall)
                py2cad(os.path.join(outputDirectory, self.filename + '_internalSupportFilletUpper.stl'), self.xInternalSupportFilletUpper, self.yInternalSupportFilletUpper, self.zInternalSupportFilletUpper)
                py2cad(os.path.join(outputDirectory, self.filename + '_internalSupportFilletLower.stl'), self.xInternalSupportFilletLower, self.yInternalSupportFilletLower, self.zInternalSupportFilletLower)
            if self.circlePrintability.lower() == 'thin':
                py2cad(os.path.join(outputDirectory, self.filename + '_internalSupportWall.stl'),        self.xInternalSupportWall, self.yInternalSupportWall, self.zInternalSupportWall)
                py2cad(os.path.join(outputDirectory, self.filename + '_internalSupportFilletUpper.stl'), self.xInternalSupportFilletUpper, self.yInternalSupportFilletUpper, self.zInternalSupportFilletUpper)

    def tongueGap(self) -> float:

        '''

        Angle the sweep stops short of a full turn by [rad].

        A ring closes on itself and carries no tongue wall, so it sweeps the full turn. A cutwater
        needs its two ends in different meridional planes with a wall between them, so it stops
        short by the angle that wall occupies at the scroll radius.

        '''

        if str(self.scrollType).lower() == 'ring':
            return 0.0

        return tongueGapAngle(self.voluteScrollRadius, self.wallThickness, self.numCrossSections)

    def generateCircleVolute(self):

        '''
        
        This method generates a circular cross section volute.

        The anchor point can be north, south, inside, outside, combinations thereof, or center.
        Specify the anchor point with one or two letters, e.g. 'n' , 'o' , or 'no'.
        Unspecified, the default is center.
        An invalid anchor point argument will also anchor center.

        Area distribution can be scedified by either hydraulic diameter or CSA on either side,
        or either hydraulic diameter or CSA on one side and number of orifices.

        Printability support enabled
        
        '''

        def drawCircleSupportThick(R):

            # scope inputs
            thetaCirc   = np.linspace(0, 2*np.pi, self.crossSectionResolution)
            yCircleWall = R*np.cos(thetaCirc)
            zCircleWall = R*np.sin(thetaCirc)
            t           = 0.00075        # printability thickness, [m]
            r           = 0.001          # printability fillet radius, [m]
            a           = np.deg2rad(30) # printability angle, [deg]->[rad]

            ## rectilinear wall
            D = R*2.5 # dummy extension length, to be trimmed later
            yRectilinear = np.array([ t/2, +t/2])
            zRectilinear = np.array([-D,     D  ])

            #### upper transition body

            ## rectilinear overhang
            # find where circle wall violates printability
            yOverhangRadial             = np.array([0, D*np.sin(a)])
            zOverhangRadial             = np.array([0, D*np.cos(a)])
            overhangRadialIntersection  = intersection(yOverhangRadial,zOverhangRadial,yCircleWall,zCircleWall)
            yOverhangRadialIntersection = overhangRadialIntersection[0][0][0]
            zOverhangRadialIntersection = overhangRadialIntersection[1][0][0]
            # draw extended linear overhang
            yOverhang = np.array([yOverhangRadialIntersection - D*np.cos(a),yOverhangRadialIntersection + D*np.cos(a)])
            zOverhang = np.array([zOverhangRadialIntersection - D*np.sin(a),zOverhangRadialIntersection + D*np.sin(a)])

            ### fillets
            yOverhangOff, zOverhangOff = parallelOffset(yOverhang,zOverhang,-r)
            ## circle wall fillet
            yCircleWallOff, zCircleWallOff = parallelOffset(yCircleWall,zCircleWall,r)
            # draw circle
            filletCenter1  = intersection(yCircleWallOff,zCircleWallOff,yOverhangOff,zOverhangOff)
            yFilletCenter1 = filletCenter1[0][0][0]
            zFilletCenter1 = filletCenter1[1][0][0]
            yFilletCircle1 = 1.005*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + yFilletCenter1
            zFilletCircle1 = 1.005*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + zFilletCenter1
            # trim overhang
            overhangIntersections = intersection(yOverhang,zOverhang,yFilletCircle1,zFilletCircle1)
            yOverhangIntersection = overhangIntersections[0][0][0]
            zOverhangIntersection = overhangIntersections[1][0][0]
            yOverhang[-1]         = yOverhangIntersection
            zOverhang[-1]         = zOverhangIntersection
            # trim wall arc
            wallIntersections     = intersection(yCircleWall,zCircleWall,yFilletCircle1,zFilletCircle1)
            yWallIntersection     = wallIntersections[0][-1][0]
            zWallIntersection     = wallIntersections[1][-1][0]
            thetaWallIntersection = np.arctan((zWallIntersection)/(yWallIntersection))
            yArcUpper = (R) * np.cos(np.linspace(thetaWallIntersection,np.pi/2,int(self.crossSectionResolution/4)))
            zArcUpper = (R) * np.sin(np.linspace(thetaWallIntersection,np.pi/2,int(self.crossSectionResolution/4)))
            # trim fillet
            thetaWallIntersection     = np.arctan((zWallIntersection-zFilletCenter1)/(yWallIntersection-yFilletCenter1))
            thetaOverhangIntersection = np.arctan((zOverhangIntersection-zFilletCenter1)/(yFilletCenter1-yOverhangIntersection))
            yFillet1 = (1.005*r) * np.cos(np.linspace(thetaWallIntersection,np.pi-thetaOverhangIntersection,int(self.crossSectionResolution/4))) + yFilletCenter1
            zFillet1 = (1.005*r) * np.sin(np.linspace(thetaWallIntersection,np.pi-thetaOverhangIntersection,int(self.crossSectionResolution/4))) + zFilletCenter1
            ## rectilinear wall fillet
            yRectilinearOff, zRectilinearOff = parallelOffset(yRectilinear,zRectilinear,-r)
            # draw circle
            filletCenter2  = intersection(yRectilinearOff,zRectilinearOff,yOverhangOff,zOverhangOff)
            yFilletCenter2 = filletCenter2 [0][0][0]
            zFilletCenter2 = filletCenter2 [1][0][0]
            yFilletCircle2 = 1.005*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + yFilletCenter2
            zFilletCircle2 = 1.005*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + zFilletCenter2
            # trim overhang
            overhangIntersections = intersection(yOverhang,zOverhang,yFilletCircle2,zFilletCircle2)
            yOverhangIntersection = overhangIntersections[0][0][0]
            zOverhangIntersection = overhangIntersections[1][0][0]
            yOverhang[0] = yOverhangIntersection
            zOverhang[0] = zOverhangIntersection
            # trim rectilinear
            rectilinearIntersections = intersection(yRectilinear,zRectilinear,yFilletCircle2,zFilletCircle2)
            yRectilinearIntersection = rectilinearIntersections[0][0][0]
            zRectilinearIntersection = rectilinearIntersections[1][0][0]
            yRectilinear[-1] = yRectilinearIntersection
            zRectilinear[-1] = zRectilinearIntersection
            # trim fillet
            thetaWallIntersection     = np.arctan((zRectilinearIntersection-zFilletCenter2)/(yFilletCenter2-yRectilinearIntersection))
            thetaOverhangIntersection = np.arctan((zOverhangIntersection-zFilletCenter2 )/(yFilletCenter2 -yOverhangIntersection))
            yFillet2 = (1.005*r) * np.cos(np.linspace(np.pi-thetaOverhangIntersection,np.pi-thetaWallIntersection,int(self.crossSectionResolution/4))) + yFilletCenter2
            zFillet2 = (1.005*r) * np.sin(np.linspace(np.pi-thetaOverhangIntersection,np.pi-thetaWallIntersection,int(self.crossSectionResolution/4))) + zFilletCenter2

            # stitch
            yTransitionBodyQuad1 = np.concatenate([np.flip(yFillet2),np.flip(yFillet1),yArcUpper])
            zTransitionBodyQuad1 = np.concatenate([np.flip(zFillet2),np.flip(zFillet1),zArcUpper+t])
            yTransitionBodyQuad2 = np.flip(-yTransitionBodyQuad1)
            zTransitionBodyQuad2 = np.flip( zTransitionBodyQuad1)
            yTransitionBodyUpper = np.concatenate([yTransitionBodyQuad1,yTransitionBodyQuad2,[yTransitionBodyQuad1[0]]])
            zTransitionBodyUpper = np.concatenate([zTransitionBodyQuad1,zTransitionBodyQuad2,[zTransitionBodyQuad1[0]]])

            #### lower transition body

            ## fillet
            # draw circle
            zRectilinearOff[-1] = 0
            filletCenter3  = intersection(yCircleWallOff,zCircleWallOff,yRectilinearOff,zRectilinearOff)
            yFilletCenter3 = filletCenter3[0][0][0]
            zFilletCenter3 = filletCenter3[1][0][0]
            yFilletCircle3 = 1.001*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + yFilletCenter3
            zFilletCircle3 = 1.001*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + zFilletCenter3
            # trim rectilinear
            zRectilinearIntersection = zFilletCenter3
            zRectilinear[0] = zRectilinearIntersection
            # trim wall arc
            wallIntersections     = intersection(yCircleWall,zCircleWall,yFilletCircle3,zFilletCircle3)
            yWallIntersection     = wallIntersections[0][-1][0]
            zWallIntersection     = wallIntersections[1][-1][0]
            thetaWallIntersection = np.arctan((yWallIntersection)/(-zWallIntersection))
            yArcLower = (R) * np.cos(np.linspace((3*np.pi/2),(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4)))
            zArcLower = (R) * np.sin(np.linspace((3*np.pi/2),(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4)))
            # trim fillet
            thetaWallIntersection = np.arctan((yWallIntersection-yFilletCenter3)/(zFilletCenter3-zWallIntersection))
            yFillet3 = (1.001*r) * np.cos(np.linspace(np.pi,(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4))) + yFilletCenter3
            zFillet3 = (1.001*r) * np.sin(np.linspace(np.pi,(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4))) + zFilletCenter3

            # stitch
            yTransitionBodyQuad4 = np.concatenate([yFillet3,np.flip(yArcLower)])
            zTransitionBodyQuad4 = np.concatenate([zFillet3,np.flip(zArcLower-t)])
            yTransitionBodyQuad3 = np.flip(-yTransitionBodyQuad4)
            zTransitionBodyQuad3 = np.flip( zTransitionBodyQuad4)
            yTransitionBodyLower = np.concatenate([yTransitionBodyQuad4,yTransitionBodyQuad3,[yTransitionBodyQuad4[0]]])
            zTransitionBodyLower = np.concatenate([zTransitionBodyQuad4,zTransitionBodyQuad3,[zTransitionBodyQuad4[0]]])

            ## lattice wall
            yLatticeWall = np.array([ yRectilinear[-1],     (-yRectilinear[-1] ),   (-yRectilinear[-1] ),   yRectilinear[-1],     yRectilinear[-1]     ])
            zLatticeWall = np.array([(zRectilinear[-1] + t),( zRectilinear[-1] + t),( zRectilinear[0] - t),(zRectilinear[0] - t),(zRectilinear[-1] + t)])

            ## store
            xInternalSupportWallCS        = np.zeros((5))
            yInternalSupportWallCS        = yLatticeWall
            zInternalSupportWallCS        = zLatticeWall
            xInternalSupportFilletUpperCS = np.zeros((int(1.5*self.crossSectionResolution+1)))
            yInternalSupportFilletUpperCS = yTransitionBodyUpper
            zInternalSupportFilletUpperCS = zTransitionBodyUpper
            xInternalSupportFilletLowerCS = np.zeros((int(self.crossSectionResolution+1)))
            yInternalSupportFilletLowerCS = yTransitionBodyLower
            zInternalSupportFilletLowerCS = zTransitionBodyLower

            ## area caulculation
            # upper fillet
            yTransitionBodyQuad1 = np.concatenate([np.flip(yFillet2),np.flip(yFillet1),yArcUpper])
            zTransitionBodyQuad1 = np.concatenate([np.flip(zFillet2),np.flip(zFillet1),zArcUpper])
            yTransitionBodyQuad2 = np.flip(-yTransitionBodyQuad1)
            zTransitionBodyQuad2 = np.flip( zTransitionBodyQuad1)
            yTransitionBodyUpperNoOverlap = np.concatenate([yTransitionBodyQuad1,yTransitionBodyQuad2,[yTransitionBodyQuad1[0]]])
            zTransitionBodyUpperNoOverlap = np.concatenate([zTransitionBodyQuad1,zTransitionBodyQuad2,[zTransitionBodyQuad1[0]]])
            # lower fillet
            yTransitionBodyQuad4 = np.concatenate([yFillet3,np.flip(yArcLower)])
            zTransitionBodyQuad4 = np.concatenate([zFillet3,np.flip(zArcLower)])
            yTransitionBodyQuad3 = np.flip(-yTransitionBodyQuad4)
            zTransitionBodyQuad3 = np.flip( zTransitionBodyQuad4)
            yTransitionBodyLowerNoOverlap = np.concatenate([yTransitionBodyQuad4,yTransitionBodyQuad3,[yTransitionBodyQuad4[0]]])
            zTransitionBodyLowerNoOverlap = np.concatenate([zTransitionBodyQuad4,zTransitionBodyQuad3,[zTransitionBodyQuad4[0]]])
            # lattice wall
            yLatticeWallNoOverlap = np.array([yRectilinear[-1],-yRectilinear[-1],-yRectilinear[-1],yRectilinear[-1],yRectilinear[-1]])
            zLatticeWallNoOverlap = np.array([zRectilinear[-1], zRectilinear[-1], zRectilinear[0], zRectilinear[0], zRectilinear[-1]])
            # trapazoidal integration
            supportArea = abs(np.trapezoid(zTransitionBodyLowerNoOverlap,yTransitionBodyLowerNoOverlap)) + \
                abs(np.trapezoid(zTransitionBodyUpperNoOverlap,yTransitionBodyUpperNoOverlap)) + \
                    abs(np.trapezoid(zLatticeWallNoOverlap,yLatticeWallNoOverlap))

            # # Debug plot
            # plt.figure()
            # plt.plot(yCircleWall,zCircleWall,'k',linewidth=2)
            # plt.plot([0,0],
            #          [0.5*D, 0.5*D],'dimgrey',linestyle=':')
            # plt.plot(yTransitionBodyUpper,zTransitionBodyUpper,'m',linewidth=2)
            # plt.plot(yTransitionBodyLower,zTransitionBodyLower,'m',linewidth=2)
            # plt.plot(yLatticeWall,zLatticeWall,'c',linewidth=2)
            # plt.plot(yTransitionBodyUpperNoOverlap,zTransitionBodyUpperNoOverlap,'r',linewidth=2)
            # plt.plot(yTransitionBodyLowerNoOverlap,zTransitionBodyLowerNoOverlap,'r',linewidth=2)
            # plt.plot(yLatticeWallNoOverlap,zLatticeWallNoOverlap,'r',linewidth=2)
            # plt.axis('equal')
            # plt.show(block = True)

            return xInternalSupportWallCS,       yInternalSupportWallCS,       zInternalSupportWallCS,\
                    xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS,\
                    xInternalSupportFilletLowerCS,yInternalSupportFilletLowerCS,zInternalSupportFilletLowerCS,\
                    supportArea

        def drawCircleSupportThin(R):

            # scope inputs
            thetaCirc   = np.linspace(0, 2*np.pi, self.crossSectionResolution)
            yCircleWall = R*np.cos(thetaCirc)
            zCircleWall = R*np.sin(thetaCirc)
            t           = 0.00075        # printability thickness, [m]
            r           = 0.001          # printability fillet radius, [m]
            a           = np.deg2rad(30) # printability angle, [deg]->[rad]

            ## upper fillet
            # arc
            thetaArc = np.linspace(0.5*np.pi - a, 0.5*np.pi + a, self.crossSectionResolution - 4)
            yArc = R * np.cos(thetaArc)
            zArc = R * np.sin(thetaArc) + t
            # tri
            triUpperRight = [R * np.cos(0.5*np.pi - a), R*np.sin(0.5*np.pi - a)]
            triUpperLeft  = [R * np.cos(0.5*np.pi + a), R*np.sin(0.5*np.pi + a)]
            dely = R *    np.sin(a)
            delz = dely * np.tan(a)
            triCenter = [triUpperRight[0] - dely, triUpperRight[1] - delz]
            yTri = [triUpperLeft[0],triCenter[0],triUpperRight[0]]
            zTri = [triUpperLeft[1],triCenter[1],triUpperRight[1]]
            # stitch
            xInternalSupportFilletUpperCS = np.zeros((self.crossSectionResolution))
            yInternalSupportFilletUpperCS = np.concatenate([yArc,yTri,[yArc[0]]])
            zInternalSupportFilletUpperCS = np.concatenate([zArc,zTri,[zArc[0]]])

            ## sheet
            xInternalSupportWallCS = [0,0]
            yInternalSupportWallCS = [0,0]
            zInternalSupportWallCS = [-R,triCenter[1]]

            # # Debug plot
            # plt.figure()
            # plt.plot(yCircleWall,zCircleWall,'k',linewidth = 2)
            # plt.plot(yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS,'c',linewidth = 3)
            # plt.plot(yInternalSupportWallCS,zInternalSupportWallCS,'m',linewidth = 3)
            # plt.axis('equal')
            # plt.show(block = True)
            # debug = 1

            supportArea = np.abs(np.trapezoid(zInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS)) + 0.002*abs(zInternalSupportWallCS[0]-zInternalSupportWallCS[1])

            return xInternalSupportWallCS,       yInternalSupportWallCS,       zInternalSupportWallCS,\
                    xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS,\
                    supportArea

        ## Define area distribution
        scroll = resolveScrollAreas(str(self.crossSectionType).lower(),
                                    interfaceArea = self.interfaceArea,
                                    interfaceHydraulicDiameter = self.interfaceHydraulicDiameter,
                                    interfaceCharacteristicLength = self.interfaceCharLen,
                                    expandedArea = self.expandedArea,
                                    expandedHydraulicDiameter = self.expandedHydraulicDiameter,
                                    expandedCharacteristicLength = self.expandedCharLen,
                                    numOrifices = self.numOrifices)
        self.interfaceArea              = scroll['interfaceArea']
        self.expandedArea               = scroll['expandedArea']
        self.interfaceHydraulicDiameter = scroll['interfaceHydraulicDiameter']
        self.expandedHydraulicDiameter  = scroll['expandedHydraulicDiameter']
        self.numOrifices                = scroll['numOrifices']

        self.crossSectionalArea = scrollAreaDistribution(self.interfaceArea, self.expandedArea,
                                                         self.numCrossSections,
                                                         str(self.scrollType).lower())
        self.hydraulicDiameter  = sectionHydraulicDiameter('circle', self.crossSectionalArea)
        radiusDistribution      = self.hydraulicDiameter/2

        ## generate inner wall CSs with center at (0,0):
        # preallocate
        xCS, yCS, zCS = [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
        if self.circlePrintability.lower() == 'thick':
            xInternalSupportWallCS,yInternalSupportWallCS,zInternalSupportWallCS = \
                [np.zeros((self.numCrossSections,5)) for _ in range(3)]
            xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS = \
                [np.zeros((self.numCrossSections,int(1.5*self.crossSectionResolution+1))) for _ in range(3)]
            xInternalSupportFilletLowerCS,yInternalSupportFilletLowerCS,zInternalSupportFilletLowerCS = \
                [np.zeros((self.numCrossSections,int(self.crossSectionResolution+1))) for _ in range(3)]
        if self.circlePrintability.lower() == 'thin':
            xInternalSupportWallCS,yInternalSupportWallCS,zInternalSupportWallCS = \
                [np.zeros((self.numCrossSections,2)) for _ in range(3)]
            xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS = \
                [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
        thetaCirc = np.linspace(0, 2*np.pi, self.crossSectionResolution)
        counter = np.zeros((self.numCrossSections))
        supportAreaDistribution = np.zeros((self.numCrossSections))
        # loop
        if str(self.progressbar).lower() == 'on':
            print('Generating Volute Cross Sections:')
        for i in tqdm(range(self.numCrossSections), disable = str(self.progressbar).lower() != 'on'):

            R = radiusDistribution[i]
            yCS[i,:] = R*np.cos(thetaCirc)
            zCS[i,:] = R*np.sin(thetaCirc)

            # draw circle support
            if self.circlePrintability.lower() == 'thick':

                xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                xInternalSupportFilletLowerCS[i,:],yInternalSupportFilletLowerCS[i,:],zInternalSupportFilletLowerCS[i,:],\
                supportArea = drawCircleSupportThick(R)

                nominalArea = np.pi*(R**2)
                usableArea = nominalArea - supportArea
                while usableArea < self.crossSectionalArea[i]: # area correction convergence loop
                    counter[i] += 1
                    R *= 1.001
                    yCS[i,:] = R*np.cos(thetaCirc)
                    zCS[i,:] = R*np.sin(thetaCirc)

                    # draw circle support
                    xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                    xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                    xInternalSupportFilletLowerCS[i,:],yInternalSupportFilletLowerCS[i,:],zInternalSupportFilletLowerCS[i,:],\
                    supportArea = drawCircleSupportThick(R)

                    nominalArea = np.pi*(R**2)
                    usableArea  = nominalArea - supportArea

                radiusDistribution[i] = R
                supportAreaDistribution[i] = supportArea

            if self.circlePrintability.lower() == 'thin':

                xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                supportArea = drawCircleSupportThin(R)

                nominalArea = np.pi*(R**2)
                usableArea = nominalArea - supportArea
                while usableArea < self.crossSectionalArea[i]: # area correction convergence loop
                    counter[i] += 1
                    R *= 1.001
                    yCS[i,:] = R*np.cos(thetaCirc)
                    zCS[i,:] = R*np.sin(thetaCirc)

                    # draw circle support
                    xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                    xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                    supportArea = drawCircleSupportThin(R)

                    nominalArea = np.pi*(R**2)
                    usableArea  = nominalArea - supportArea

                radiusDistribution[i] = R

            # move to anchor point
            dy, dz = anchorOffset(self.anchorBy, R)
            yCS[i,:]                           += dy
            zCS[i,:]                           += dz
            if self.circlePrintability.lower() == 'thick':
                yInternalSupportWallCS[i,:]        += dy
                yInternalSupportFilletUpperCS[i,:] += dy
                yInternalSupportFilletLowerCS[i,:] += dy
                zInternalSupportWallCS[i,:]        += dz
                zInternalSupportFilletUpperCS[i,:] += dz
                zInternalSupportFilletLowerCS[i,:] += dz
            if self.circlePrintability.lower() == 'thin':
                yInternalSupportWallCS[i,:]        += dy
                yInternalSupportFilletUpperCS[i,:] += dy
                zInternalSupportWallCS[i,:]        += dz
                zInternalSupportFilletUpperCS[i,:] += dz

        # update values to refelct circle cupport area corrections
        self.supportArea        = supportAreaDistribution
        self.hydraulicDiameter  = radiusDistribution*2
        self.crossSectionalArea = np.pi*(radiusDistribution**2)

        # generate shell
        if self.wallThickness is not None or self.wallHoopStress is not None:
            # Each section is a tube on its own bend radius, the radius of its centre, which is
            # where the toroidal correction to the hoop stress comes from.
            bendRadius = self.voluteScrollRadius + np.array(
                [anchorOffset(self.anchorBy, R)[0] for R in radiusDistribution])
            yShellCS, zShellCS, _, _, wallThickness= dynamicEggShell(yCS,zCS,
                                                        self.wallThickness,
                                                        self.wallHoopStress, self.pressureDifferential, self.hydraulicDiameter,
                                                        bendRadius, self.minWallThickness)
            self.wallThickness = wallThickness
            xShellCS = np.zeros_like(xCS)
            # catch inverted wall
            if abs(np.trapezoid(yShellCS[0,:],zShellCS[0,:])) < abs(np.trapezoid(yCS[0,:],zCS[0,:])):
                self.wallThickness *= -1
                yShellCS, zShellCS, _, _, wallThickness= dynamicEggShell(yCS,zCS,
                                                        self.wallThickness)
            self.wallThickness = abs(wallThickness)

        # move cross sections to correct radius
        if self.alignWallBy == 'inner':
            yCS += self.voluteScrollRadius
            if self.wallThickness is not None:
                yShellCS += self.voluteScrollRadius
            if self.circlePrintability.lower() ==  'thick':
                yInternalSupportWallCS += self.voluteScrollRadius
                yInternalSupportFilletUpperCS += self.voluteScrollRadius
                yInternalSupportFilletLowerCS += self.voluteScrollRadius
            if self.circlePrintability.lower() ==  'thin':
                yInternalSupportWallCS += self.voluteScrollRadius
                yInternalSupportFilletUpperCS += self.voluteScrollRadius
        elif self.alignWallBy == 'outer':

            if self.wallThickness is None:
                print('No outer wall to align by.')
                yCS += self.voluteScrollRadius
                if self.wallThickness is not None:
                    yShellCS += self.voluteScrollRadius
                if self.circlePrintability.lower() ==  'thick':
                    yInternalSupportWallCS += self.voluteScrollRadius
                    yInternalSupportFilletUpperCS += self.voluteScrollRadius
                    yInternalSupportFilletLowerCS += self.voluteScrollRadius
                if self.circlePrintability.lower() ==  'thin':
                    yInternalSupportWallCS += self.voluteScrollRadius
                    yInternalSupportFilletUpperCS += self.voluteScrollRadius

            elif self.wallThickness is not None:
                y1p = np.zeros((self.numCrossSections))
                z1p = np.zeros((self.numCrossSections))
                match self.anchorBy.lower():
                    case 'n':
                        z1p += self.wallThickness
                    case 's':
                        z1p -= self.wallThickness
                    case 'o':
                        y1p += self.wallThickness
                    case 'i':
                        y1p -= self.wallThickness
                    case 'no':
                        y1p += self.wallThickness/np.sqrt(2)
                        z1p += self.wallThickness/np.sqrt(2)
                    case 'so':
                        y1p += self.wallThickness/np.sqrt(2)
                        z1p -= self.wallThickness/np.sqrt(2)
                    case 'ni':
                        y1p -= self.wallThickness/np.sqrt(2)
                        z1p += self.wallThickness/np.sqrt(2)
                    case 'si':
                        y1p -= self.wallThickness/np.sqrt(2)
                        z1p -= self.wallThickness/np.sqrt(2)
                for i in range(self.numCrossSections):
                    yCS[i,:] += self.voluteScrollRadius - y1p[i]
                    zCS[i,:] += -z1p[i]
                    yShellCS[i,:] += self.voluteScrollRadius - y1p[i]
                    zShellCS[i,:] += -z1p[i]
                    if self.circlePrintability.lower() ==  'thick':
                        yInternalSupportWallCS[i,:]        += self.voluteScrollRadius - y1p[i]
                        zInternalSupportWallCS[i,:]        += -z1p[i]
                        yInternalSupportFilletUpperCS[i,:] += self.voluteScrollRadius - y1p[i]
                        zInternalSupportFilletUpperCS[i,:] += -z1p[i]
                        yInternalSupportFilletLowerCS[i,:] += self.voluteScrollRadius - y1p[i]
                        zInternalSupportFilletLowerCS[i,:] += -z1p[i]
                    if self.circlePrintability.lower() ==  'thin':
                        yInternalSupportWallCS[i,:]        += self.voluteScrollRadius - y1p[i]
                        zInternalSupportWallCS[i,:]        += -z1p[i]
                        yInternalSupportFilletUpperCS[i,:] += self.voluteScrollRadius - y1p[i]
                        zInternalSupportFilletUpperCS[i,:] += -z1p[i]
        else:
            raise Exception('Invalid wall alignment argument. Please specify inner or outer.')

        # roll cross sections about scroll axis to create mesh
        sweep = 2*np.pi - self.tongueGap()
        if self.scrollDirection.lower() == 'cw':
            rollAngle = np.linspace(0, sweep, self.numCrossSections)
        elif self.scrollDirection.lower() == 'ccw':
            rollAngle = np.linspace(sweep, 0, self.numCrossSections)
        else:
            raise Exception('Invalid scroll direction argument. Please specify cw or ccw.')
        xVolute, yVolute, zVolute = [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
        rollAboutAxis(rollAngle, (xCS, yCS, zCS),
                      (xVolute, yVolute, zVolute))

        # roll outer wall cross sections about scroll axis to create mesh
        if self.wallThickness is not None:
            xShell, yShell, zShell = [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
            rollAboutAxis(rollAngle, (xShellCS, yShellCS, zShellCS),
                          (xShell, yShell, zShell))

        # roll inner support cross sections about scroll axis to create mesh
        if self.circlePrintability.lower() == 'thick':
            xInternalSupportWall, yInternalSupportWall, zInternalSupportWall =                      \
                [np.zeros((self.numCrossSections,5)) for _ in range(3)]
            xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper = \
                [np.zeros((self.numCrossSections,int(1.5*self.crossSectionResolution+1))) for _ in range(3)]
            xInternalSupportFilletLower, yInternalSupportFilletLower, zInternalSupportFilletLower = \
                [np.zeros((self.numCrossSections,int(self.crossSectionResolution+1))) for _ in range(3)]
            rollAboutAxis(rollAngle, (xInternalSupportWallCS, yInternalSupportWallCS, zInternalSupportWallCS),
                          (xInternalSupportWall, yInternalSupportWall, zInternalSupportWall))
            rollAboutAxis(rollAngle, (xInternalSupportFilletUpperCS, yInternalSupportFilletUpperCS, zInternalSupportFilletUpperCS),
                          (xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper))
            rollAboutAxis(rollAngle, (xInternalSupportFilletLowerCS, yInternalSupportFilletLowerCS, zInternalSupportFilletLowerCS),
                          (xInternalSupportFilletLower, yInternalSupportFilletLower, zInternalSupportFilletLower))
        if self.circlePrintability.lower() == 'thin':
            xInternalSupportWall, yInternalSupportWall, zInternalSupportWall =                      \
                [np.zeros((self.numCrossSections,2)) for _ in range(3)]
            xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper = \
                [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
            rollAboutAxis(rollAngle, (xInternalSupportWallCS, yInternalSupportWallCS, zInternalSupportWallCS),
                          (xInternalSupportWall, yInternalSupportWall, zInternalSupportWall))
            rollAboutAxis(rollAngle, (xInternalSupportFilletUpperCS, yInternalSupportFilletUpperCS, zInternalSupportFilletUpperCS),
                          (xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper))

        # axial location
        zVolute += self.axialOffset
        if self.wallThickness is not None:
            zShell += self.axialOffset
        if self.circlePrintability.lower() == 'thick':
            zInternalSupportWall        += self.axialOffset
            zInternalSupportFilletUpper += self.axialOffset
            zInternalSupportFilletLower += self.axialOffset
        if self.circlePrintability.lower() == 'thin':
            zInternalSupportWall        += self.axialOffset
            zInternalSupportFilletUpper += self.axialOffset

        # assign
        self.xVolute = xVolute
        self.yVolute = yVolute
        self.zVolute = zVolute
        if self.wallThickness is not None:
            self.xShell = xShell
            self.yShell = yShell
            self.zShell = zShell
        if self.circlePrintability.lower() == 'thick':
            self.xInternalSupportWall        = xInternalSupportWall
            self.yInternalSupportWall        = yInternalSupportWall
            self.zInternalSupportWall        = zInternalSupportWall
            self.xInternalSupportFilletUpper = xInternalSupportFilletUpper
            self.yInternalSupportFilletUpper = yInternalSupportFilletUpper
            self.zInternalSupportFilletUpper = zInternalSupportFilletUpper
            self.xInternalSupportFilletLower = xInternalSupportFilletLower
            self.yInternalSupportFilletLower = yInternalSupportFilletLower
            self.zInternalSupportFilletLower = zInternalSupportFilletLower
        if self.circlePrintability.lower() == 'thin':
            self.xInternalSupportWall        = xInternalSupportWall
            self.yInternalSupportWall        = yInternalSupportWall
            self.zInternalSupportWall        = zInternalSupportWall
            self.xInternalSupportFilletUpper = xInternalSupportFilletUpper
            self.yInternalSupportFilletUpper = yInternalSupportFilletUpper
            self.zInternalSupportFilletUpper = zInternalSupportFilletUpper

    def generateSquarcVolute(self):

        '''
        
        get squarcked, idiot.

        This cross section is a circle squared off at the upper inner corner.
        The printability angle is defined relative to horizontal (XY plane, plane of the scroll)
        The printability angle is maintained as the radius of the arc changes.

        The area distribution can be bounded either by hydraulic diameter or CSA on
        both the interface and expanded sides, or either hydraulic diameter or CSA on one side
        and number of orifices.

        '''

        def drawCircleSupportThick(R):

            # scope inputs
            thetaCirc   = np.linspace(0, 2*np.pi, self.crossSectionResolution*4)
            yCircleWall = R*np.cos(thetaCirc)
            zCircleWall = R*np.sin(thetaCirc)
            t           = 0.00075        # printability thickness, [m]
            r           = 0.001          # printability fillet radius, [m]
            a           = np.deg2rad(30) # printability angle, [deg]->[rad]

            ## rectilinear wall
            D = 2*R # dummy extension length, to be trimmed later
            yRectilinear = np.array([ t/2, t/2])
            zRectilinear = np.array([-D,   D  ])

            #### upper transition body

            ## rectilinear overhang
            # find where circle wall violates printability
            yOverhangRadial             = np.array([0, D*np.sin(a)])
            zOverhangRadial             = np.array([0, D*np.cos(a)])
            overhangRadialIntersection  = intersection(yOverhangRadial,zOverhangRadial,yCircleWall,zCircleWall)
            yOverhangRadialIntersection = overhangRadialIntersection[0][0][0]
            zOverhangRadialIntersection = overhangRadialIntersection[1][0][0]
            # draw extended linear overhang
            yOverhang = np.array([yOverhangRadialIntersection - D*np.cos(a),yOverhangRadialIntersection + D*np.cos(a)])
            zOverhang = np.array([zOverhangRadialIntersection - D*np.sin(a),zOverhangRadialIntersection + D*np.sin(a)])

            ### fillets
            yOverhangOff, zOverhangOff = parallelOffset(yOverhang,zOverhang,-r)
            ## circle wall fillet
            yCircleWallOff, zCircleWallOff = parallelOffset(yCircleWall,zCircleWall,r)
            # draw circle
            filletCenter1  = intersection(yCircleWallOff,zCircleWallOff,yOverhangOff,zOverhangOff)
            yFilletCenter1 = filletCenter1[0][0][0]
            zFilletCenter1 = filletCenter1[1][0][0]
            yFilletCircle1 = 1.005*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + yFilletCenter1
            zFilletCircle1 = 1.005*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + zFilletCenter1
            # trim overhang
            overhangIntersections = intersection(yOverhang,zOverhang,yFilletCircle1,zFilletCircle1)
            yOverhangIntersection = overhangIntersections[0][0][0]
            zOverhangIntersection = overhangIntersections[1][0][0]
            yOverhang[-1]         = yOverhangIntersection
            zOverhang[-1]         = zOverhangIntersection
            # trim wall arc
            wallIntersections     = intersection(yCircleWall,zCircleWall,yFilletCircle1,zFilletCircle1)
            yWallIntersection1     = wallIntersections[0][-1][0]
            zWallIntersection1     = wallIntersections[1][-1][0]
            thetaWallIntersection = np.arctan((zWallIntersection1)/(yWallIntersection1))
            yArcUpper = (L) * np.cos(np.linspace(thetaWallIntersection,np.pi/2,int(self.crossSectionResolution/4)))
            zArcUpper = (L) * np.sin(np.linspace(thetaWallIntersection,np.pi/2,int(self.crossSectionResolution/4)))
            # trim fillet
            thetaWallIntersection     = np.arctan((zWallIntersection1-zFilletCenter1)/(yWallIntersection1-yFilletCenter1))
            thetaOverhangIntersection = np.arctan((zOverhangIntersection-zFilletCenter1)/(yFilletCenter1-yOverhangIntersection))
            yFillet1 = (1.005*r) * np.cos(np.linspace(thetaWallIntersection,np.pi-thetaOverhangIntersection,int(self.crossSectionResolution/4))) + yFilletCenter1
            zFillet1 = (1.005*r) * np.sin(np.linspace(thetaWallIntersection,np.pi-thetaOverhangIntersection,int(self.crossSectionResolution/4))) + zFilletCenter1
            ## rectilinear wall fillet
            yRectilinearOff, zRectilinearOff = parallelOffset(yRectilinear,zRectilinear,-r)
            # draw circle
            filletCenter2  = intersection(yRectilinearOff,zRectilinearOff,yOverhangOff,zOverhangOff)
            yFilletCenter2 = filletCenter2 [0][0][0]
            zFilletCenter2 = filletCenter2 [1][0][0]
            yFilletCircle2 = 1.005*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + yFilletCenter2
            zFilletCircle2 = 1.005*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*4)) + zFilletCenter2
            # trim overhang
            overhangIntersections = intersection(yOverhang,zOverhang,yFilletCircle2,zFilletCircle2)
            yOverhangIntersection = overhangIntersections[0][0][0]
            zOverhangIntersection = overhangIntersections[1][0][0]
            yOverhang[0] = yOverhangIntersection
            zOverhang[0] = zOverhangIntersection
            # trim rectilinear
            rectilinearIntersections = intersection(yRectilinear,zRectilinear,yFilletCircle2,zFilletCircle2)
            yRectilinearIntersection = rectilinearIntersections[0][0][0]
            zRectilinearIntersection = rectilinearIntersections[1][0][0]
            yRectilinear[-1] = yRectilinearIntersection
            zRectilinear[-1] = zRectilinearIntersection
            # trim fillet
            thetaWallIntersection     = np.arctan((zRectilinearIntersection-zFilletCenter2)/(yFilletCenter2-yRectilinearIntersection))
            thetaOverhangIntersection = np.arctan((zOverhangIntersection-zFilletCenter2 )/(yFilletCenter2 -yOverhangIntersection))
            yFillet2 = (1.005*r) * np.cos(np.linspace(np.pi-thetaOverhangIntersection,np.pi-thetaWallIntersection,int(self.crossSectionResolution/4))) + yFilletCenter2
            zFillet2 = (1.005*r) * np.sin(np.linspace(np.pi-thetaOverhangIntersection,np.pi-thetaWallIntersection,int(self.crossSectionResolution/4))) + zFilletCenter2
            # stitch
            yTransitionBodyQuad1 = np.concatenate([np.flip(yFillet2),np.flip(yFillet1),yArcUpper])
            zTransitionBodyQuad1 = np.concatenate([np.flip(zFillet2),np.flip(zFillet1),zArcUpper+t])
            yTransitionBodyQuad2 = np.flip(-yTransitionBodyQuad1)
            zTransitionBodyQuad2 = np.flip( zTransitionBodyQuad1)
            yTransitionBodyUpper = np.concatenate([yTransitionBodyQuad1,yTransitionBodyQuad2,[yTransitionBodyQuad1[0]]])
            zTransitionBodyUpper = np.concatenate([zTransitionBodyQuad1,zTransitionBodyQuad2,[zTransitionBodyQuad1[0]]])

            #### lower transition body

            ## fillet right
            # draw circle
            zRectilinearOff[-1] = 0
            filletCenter3  = intersection(yCircleWallOff,zCircleWallOff,yRectilinearOff,zRectilinearOff)
            yFilletCenter3 = filletCenter3[0][0][0]
            zFilletCenter3 = filletCenter3[1][0][0]
            yFilletCircle3 = 1.001*r * np.cos(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + yFilletCenter3
            zFilletCircle3 = 1.001*r * np.sin(np.linspace(0,2*np.pi,self.crossSectionResolution*2)) + zFilletCenter3
            # trim rectilinear
            zRectilinearIntersection = zFilletCenter3
            zRectilinear[0] = zRectilinearIntersection
            # trim wall arc
            wallIntersections     = intersection(yCircleWall,zCircleWall,yFilletCircle3,zFilletCircle3)
            yWallIntersection     = wallIntersections[0][-1][0]
            zWallIntersection     = wallIntersections[1][-1][0]
            thetaWallIntersection = np.arctan((yWallIntersection)/(-zWallIntersection))
            yArcLower = (L) * np.cos(np.linspace((3*np.pi/2),(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4)))
            zArcLower = (L) * np.sin(np.linspace((3*np.pi/2),(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4)))
            # trim fillet
            thetaWallIntersection = np.arctan((yWallIntersection-yFilletCenter3)/(zFilletCenter3-zWallIntersection))
            yFillet3 = (1.001*r) * np.cos(np.linspace(np.pi,(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4))) + yFilletCenter3
            zFillet3 = (1.001*r) * np.sin(np.linspace(np.pi,(3*np.pi/2)+thetaWallIntersection,int(self.crossSectionResolution/4))) + zFilletCenter3
            ## fillet left
            # draw circle
            rL = R-abs(zFilletCenter3)
            yFilletCenterL = -(t/2) - rL
            zFilletCenterL = zFilletCenter3
            # trim fillet
            yFilletL = (1.001*rL) * np.cos(np.linspace(-np.pi/2,0,int(self.crossSectionResolution/4))) + yFilletCenterL
            zFilletL = (1.001*rL) * np.sin(np.linspace(-np.pi/2,0,int(self.crossSectionResolution/4))) + zFilletCenterL
            # stitch
            yTransitionBodyQuad4 = np.concatenate([yFillet3,np.flip(yArcLower)])
            zTransitionBodyQuad4 = np.concatenate([zFillet3,np.flip(zArcLower-t)])
            yTransitionBodyQuad3 = np.concatenate([[yFilletL[0]],yFilletL])
            zTransitionBodyQuad3 = np.concatenate([[-R-t],       zFilletL])
            yTransitionBodyLower = np.concatenate([yTransitionBodyQuad4,yTransitionBodyQuad3,[yTransitionBodyQuad4[0]]])
            zTransitionBodyLower = np.concatenate([zTransitionBodyQuad4,zTransitionBodyQuad3,[zTransitionBodyQuad4[0]]])

            ## lattice wall
            yLatticeWall = np.array([ yRectilinear[-1],     (-yRectilinear[-1] ),   (-yRectilinear[-1] ),   yRectilinear[-1],     yRectilinear[-1]     ])
            zLatticeWall = np.array([(zRectilinear[-1] + t),( zRectilinear[-1] + t),( zRectilinear[0] - t),(zRectilinear[0] - t),(zRectilinear[-1] + t)])

            ## store
            xInternalSupportWallCS        = np.zeros((5))
            yInternalSupportWallCS        = yLatticeWall
            zInternalSupportWallCS        = zLatticeWall
            xInternalSupportFilletUpperCS = np.zeros((int(1.5*self.crossSectionResolution+1)))
            yInternalSupportFilletUpperCS = yTransitionBodyUpper
            zInternalSupportFilletUpperCS = zTransitionBodyUpper
            xInternalSupportFilletLowerCS = np.zeros((int(0.75*self.crossSectionResolution+2)))
            yInternalSupportFilletLowerCS = yTransitionBodyLower
            zInternalSupportFilletLowerCS = zTransitionBodyLower

            ## area caulculation
            # upper fillet
            yTransitionBodyQuad1 = np.concatenate([np.flip(yFillet2),np.flip(yFillet1),yArcUpper])
            zTransitionBodyQuad1 = np.concatenate([np.flip(zFillet2),np.flip(zFillet1),zArcUpper])
            yTransitionBodyQuad2 = np.flip(-yTransitionBodyQuad1)
            zTransitionBodyQuad2 = np.flip( zTransitionBodyQuad1)
            yTransitionBodyUpperNoOverlap = np.concatenate([yTransitionBodyQuad1,yTransitionBodyQuad2,[yTransitionBodyQuad1[0]]])
            zTransitionBodyUpperNoOverlap = np.concatenate([zTransitionBodyQuad1,zTransitionBodyQuad2,[zTransitionBodyQuad1[0]]])
            # lower fillet
            yTransitionBodyQuad4 = np.concatenate([yFillet3,np.flip(yArcLower)])
            zTransitionBodyQuad4 = np.concatenate([zFillet3,np.flip(zArcLower)])
            yTransitionBodyQuad3 = np.concatenate([[yFilletL[0]],yFilletL])
            zTransitionBodyQuad3 = np.concatenate([[zFilletL[0]],zFilletL])
            yTransitionBodyLowerNoOverlap = np.concatenate([yTransitionBodyQuad4,yTransitionBodyQuad3,[yTransitionBodyQuad4[0]]])
            zTransitionBodyLowerNoOverlap = np.concatenate([zTransitionBodyQuad4,zTransitionBodyQuad3,[zTransitionBodyQuad4[0]]])
            # lattice wall
            yLatticeWallNoOverlap = np.array([yRectilinear[-1],-yRectilinear[-1],-yRectilinear[-1],yRectilinear[-1],yRectilinear[-1]])
            zLatticeWallNoOverlap = np.array([zRectilinear[-1], zRectilinear[-1], zRectilinear[0], zRectilinear[0], zRectilinear[-1]])
            # trapazoidal integration
            supportArea = abs(np.trapezoid(zTransitionBodyLowerNoOverlap,yTransitionBodyLowerNoOverlap)) + \
                abs(np.trapezoid(zTransitionBodyUpperNoOverlap,yTransitionBodyUpperNoOverlap)) + \
                    abs(np.trapezoid(zLatticeWallNoOverlap,yLatticeWallNoOverlap))

            # ySquarc = np.concatenate([[-R],R * np.cos(np.linspace(-np.pi/2,np.pi,self.crossSectionResolution)),[-R]])
            # zSquarc = np.concatenate([[-R],R * np.sin(np.linspace(-np.pi/2,np.pi,self.crossSectionResolution)),[-R]])
            # # Debug plot
            # plt.figure()
            # plt.plot(yCircleWall,zCircleWall,'grey',linestyle='--')
            # plt.plot(ySquarc,zSquarc,'k',linewidth=2)
            # plt.plot([0,0],
            #          [0.5*D, 0.5*D],'grey',linestyle=':')
            # plt.plot(yTransitionBodyUpper,zTransitionBodyUpper,'y',linewidth=2)
            # plt.plot(yTransitionBodyLower,zTransitionBodyLower,'m',linewidth=2)
            # plt.plot(yLatticeWall,zLatticeWall,'c',linewidth=2)
            # # plt.plot(yTransitionBodyUpperNoOverlap,zTransitionBodyUpperNoOverlap,'r',linewidth=2)
            # # plt.plot(yTransitionBodyLowerNoOverlap,zTransitionBodyLowerNoOverlap,'r',linewidth=2)
            # # plt.plot(yLatticeWallNoOverlap,zLatticeWallNoOverlap,'r',linewidth=2)
            # plt.plot(yFillet1,zFillet1,'m')
            # plt.plot(yArcUpper,zArcUpper,'b',linewidth=2)
            # plt.scatter([yWallIntersection1],[zWallIntersection1],50,color='m',marker='*')
            # plt.axis('equal')
            # plt.show(block = True)

            return xInternalSupportWallCS,       yInternalSupportWallCS,       zInternalSupportWallCS,\
                   xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS,\
                   xInternalSupportFilletLowerCS,yInternalSupportFilletLowerCS,zInternalSupportFilletLowerCS,\
                   supportArea

        def drawCircleSupportThin(R):

            # scope inputs
            thetaCirc   = np.linspace(0, 2*np.pi, self.crossSectionResolution)
            yCircleWall = R*np.cos(thetaCirc)
            zCircleWall = R*np.sin(thetaCirc)
            t           = 0.00075        # printability thickness, [m]
            r           = 0.001          # printability fillet radius, [m]
            a           = np.deg2rad(30) # printability angle, [deg]->[rad]

            ## upper fillet
            # arc
            thetaArc = np.linspace(0.5*np.pi - a, 0.5*np.pi + a, self.crossSectionResolution - 4)
            yArc = R * np.cos(thetaArc)
            zArc = R * np.sin(thetaArc) + t
            # tri
            triUpperRight = [R * np.cos(0.5*np.pi - a), R*np.sin(0.5*np.pi - a)]
            triUpperLeft  = [R * np.cos(0.5*np.pi + a), R*np.sin(0.5*np.pi + a)]
            dely = R *    np.sin(a)
            delz = dely * np.tan(a)
            triCenter = [triUpperRight[0] - dely, triUpperRight[1] - delz]
            yTri = np.concatenate([triUpperLeft[0],triCenter[0],triUpperRight[0]])
            zTri = np.concatenate([triUpperLeft[1],triCenter[1],triUpperRight[1]])
            # stitch
            xInternalSupportFilletUpperCS = np.zeros((self.crossSectionResolution))
            yInternalSupportFilletUpperCS = np.concatenate([yArc,yTri,[yArc[0]]])
            zInternalSupportFilletUpperCS = np.concatenate([zArc,zTri,[zArc[0]]])

            ## sheet
            xInternalSupportWallCS = np.array([0,0])
            yInternalSupportWallCS = np.array([0,0] )
            zInternalSupportWallCS = np.array([-R,triCenter[1]]).reshape(2)

            # # Debug plot
            # plt.figure()
            # plt.plot(yCircleWall,zCircleWall,'k',linewidth = 2)
            # plt.plot(yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS,'c',linewidth = 3)
            # plt.plot(yInternalSupportWallCS,zInternalSupportWallCS,'m',linewidth = 3)
            # plt.axis('equal')
            # plt.show(block = True)
            # debug = 1

            supportArea = abs(np.trapezoid(zInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS)) + 0.002*abs(zInternalSupportWallCS[0]-zInternalSupportWallCS[1])

            return xInternalSupportWallCS,       yInternalSupportWallCS,       zInternalSupportWallCS,\
                    xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS,\
                    supportArea

        ## Define area distribution
        scroll = resolveScrollAreas(str(self.crossSectionType).lower(),
                                    interfaceArea = self.interfaceArea,
                                    interfaceHydraulicDiameter = self.interfaceHydraulicDiameter,
                                    interfaceCharacteristicLength = self.interfaceCharLen,
                                    expandedArea = self.expandedArea,
                                    expandedHydraulicDiameter = self.expandedHydraulicDiameter,
                                    expandedCharacteristicLength = self.expandedCharLen,
                                    numOrifices = self.numOrifices)
        self.interfaceArea              = scroll['interfaceArea']
        self.expandedArea               = scroll['expandedArea']
        self.interfaceHydraulicDiameter = scroll['interfaceHydraulicDiameter']
        self.expandedHydraulicDiameter  = scroll['expandedHydraulicDiameter']
        self.numOrifices                = scroll['numOrifices']

        self.crossSectionalArea = scrollAreaDistribution(self.interfaceArea, self.expandedArea,
                                                         self.numCrossSections,
                                                         str(self.scrollType).lower())
        charLenDistribution     = characteristicLengthFromArea('squarc', self.crossSectionalArea)
        self.hydraulicDiameter  = sectionHydraulicDiameter('squarc', self.crossSectionalArea)

        tiltAngle = -np.deg2rad(self.printabilityAngle)

        ## generate inner wall CSs with corner at (0,0):
        # preallocate
        xCS, yCS, zCS = [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
        if self.circlePrintability.lower() == 'thick':
            xInternalSupportWallCS,yInternalSupportWallCS,zInternalSupportWallCS = \
                [np.zeros((self.numCrossSections,5)) for _ in range(3)]
            xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS = \
                [np.zeros((self.numCrossSections,int(1.5*self.crossSectionResolution+1))) for _ in range(3)]
            xInternalSupportFilletLowerCS,yInternalSupportFilletLowerCS,zInternalSupportFilletLowerCS = \
                [np.zeros((self.numCrossSections,int(0.75*self.crossSectionResolution+2))) for _ in range(3)]
        if self.circlePrintability.lower() == 'thin':
            xInternalSupportWallCS,yInternalSupportWallCS,zInternalSupportWallCS = \
                [np.zeros((self.numCrossSections,2)) for _ in range(3)]
            xInternalSupportFilletUpperCS,yInternalSupportFilletUpperCS,zInternalSupportFilletUpperCS = \
                [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
        thetaCirc = np.linspace(0.5*np.pi + tiltAngle, -np.pi + tiltAngle, self.crossSectionResolution - 2)
        counter = np.zeros((self.numCrossSections))
        # loop
        if str(self.progressbar).lower() == 'on':
            print('Generating Volute Cross Sections:')
        for i in tqdm(range(self.numCrossSections), disable = str(self.progressbar).lower() != 'on'):

            L = charLenDistribution[i]
            yCirc = L*np.sin(thetaCirc) - L*(np.cos(tiltAngle) - np.sin(tiltAngle))
            zCirc = L*np.cos(thetaCirc) + L*(np.cos(tiltAngle) + np.sin(tiltAngle))
            yCSi  = np.concatenate([[0],yCirc,[0]])
            zCSi  = np.concatenate([[0],zCirc,[0]])
            yCS[i,:] = -yCSi
            zCS[i,:] = -zCSi

            # draw circle support
            if self.circlePrintability.lower() == 'thick':

                xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                xInternalSupportFilletLowerCS[i,:],yInternalSupportFilletLowerCS[i,:],zInternalSupportFilletLowerCS[i,:],\
                supportArea = drawCircleSupportThick(L)

                nominalArea = (L**2)*(1+0.75*np.pi)
                usableArea = nominalArea - supportArea
                while usableArea < self.crossSectionalArea[i]:  # area correction convergence loop
                    counter[i] += 1
                    L *= 1.001
                    yCirc = L*np.sin(thetaCirc) - L*(np.cos(tiltAngle) - np.sin(tiltAngle))
                    zCirc = L*np.cos(thetaCirc) + L*(np.cos(tiltAngle) + np.sin(tiltAngle))
                    yCSi  = np.concatenate([[0],yCirc,[0]])
                    zCSi  = np.concatenate([[0],zCirc,[0]])
                    yCS[i,:] = -yCSi
                    zCS[i,:] = -zCSi

                    # draw circle support
                    xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                    xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                    xInternalSupportFilletLowerCS[i,:],yInternalSupportFilletLowerCS[i,:],zInternalSupportFilletLowerCS[i,:],\
                    supportArea = drawCircleSupportThick(L)

                    nominalArea = (L**2)*(1+0.75*np.pi)
                    usableArea  = nominalArea - supportArea

                    yInternalSupportWallCS[i,:]        += L
                    zInternalSupportWallCS[i,:]        += L
                    yInternalSupportFilletUpperCS[i,:] += L
                    zInternalSupportFilletUpperCS[i,:] += L
                    yInternalSupportFilletLowerCS[i,:] += L
                    zInternalSupportFilletLowerCS[i,:] += L

                charLenDistribution[i] = L

            if self.circlePrintability.lower() == 'thin':

                xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                supportArea = drawCircleSupportThin(L)

                nominalArea = (L**2)*(1+0.75*np.pi)
                usableArea = nominalArea - supportArea
                while usableArea < self.crossSectionalArea[i]:  # area correction convergence loop
                    counter[i] += 1
                    L *= 1.001
                    yCirc = L*np.sin(thetaCirc) - L*(np.cos(tiltAngle) - np.sin(tiltAngle))
                    zCirc = L*np.cos(thetaCirc) + L*(np.cos(tiltAngle) + np.sin(tiltAngle))
                    yCSi  = np.concatenate([[0],yCirc,[0]])
                    zCSi  = np.concatenate([[0],zCirc,[0]])
                    yCS[i,:] = -yCSi
                    zCS[i,:] = -zCSi

                    # draw circle support
                    xInternalSupportWallCS[i,:],       yInternalSupportWallCS[i,:],       zInternalSupportWallCS[i,:],       \
                    xInternalSupportFilletUpperCS[i,:],yInternalSupportFilletUpperCS[i,:],zInternalSupportFilletUpperCS[i,:],\
                    supportArea = drawCircleSupportThin(L)

                    nominalArea = (L**2)*(1+0.75*np.pi)
                    usableArea  = nominalArea - supportArea

                    yInternalSupportWallCS[i,:]        += L
                    zInternalSupportWallCS[i,:]        += L
                    yInternalSupportFilletUpperCS[i,:] += L
                    zInternalSupportFilletUpperCS[i,:] += L

                charLenDistribution[i] = L

        # update values to refelct circle cupport area corrections
        self.crossSectionArea  = (charLenDistribution**2)*(1+0.75*np.pi)
        self.hydraulicDiameter = 4*self.crossSectionalArea / ((1.5*np.pi*charLenDistribution) + (2*charLenDistribution))

        # generate shell
        if self.wallThickness is not None or self.wallHoopStress is not None:
            # A squircle is drawn with its corner on the scroll radius, so its centre, and the bend
            # radius the toroidal correction reads, sits one characteristic length outboard.
            bendRadius = self.voluteScrollRadius + charLenDistribution
            yShellCS, zShellCS, y1p, z1p, wallThickness= dynamicEggShell(yCS,zCS,
                                                        self.wallThickness,
                                                        self.wallHoopStress, self.pressureDifferential, self.hydraulicDiameter,
                                                        bendRadius, self.minWallThickness)
            self.wallThickness = wallThickness
            xShellCS = np.zeros_like(xCS)
            # catch inverted wall
            if abs(np.trapezoid(yShellCS[0,:],zShellCS[0,:])) < abs(np.trapezoid(yCS[0,:],zCS[0,:])):
                self.wallThickness *= -1
                yShellCS, zShellCS, _, _, wallThickness= dynamicEggShell(yCS,zCS,
                                                        self.wallThickness)
            self.wallThickness = abs(wallThickness)

        # move cross sections to correct radius
        if self.alignWallBy == 'inner':
            yCS += self.voluteScrollRadius
            if self.wallThickness is not None:
                yShellCS += self.voluteScrollRadius
            if self.circlePrintability.lower() ==  'thick':
                yInternalSupportWallCS += self.voluteScrollRadius
                yInternalSupportFilletUpperCS += self.voluteScrollRadius
                yInternalSupportFilletLowerCS += self.voluteScrollRadius
            if self.circlePrintability.lower() ==  'thin':
                yInternalSupportWallCS += self.voluteScrollRadius
                yInternalSupportFilletUpperCS += self.voluteScrollRadius
        elif self.alignWallBy == 'outer':

            if self.wallThickness is None:
                print('No outer wall to align by.')
                yCS += self.voluteScrollRadius
                if self.wallThickness is not None:
                    yShellCS += self.voluteScrollRadius
                if self.circlePrintability.lower() ==  'thick':
                    yInternalSupportWallCS += self.voluteScrollRadius
                    yInternalSupportFilletUpperCS += self.voluteScrollRadius
                    yInternalSupportFilletLowerCS += self.voluteScrollRadius
                if self.circlePrintability.lower() ==  'thin':
                    yInternalSupportWallCS += self.voluteScrollRadius
                    yInternalSupportFilletUpperCS += self.voluteScrollRadius
            elif self.wallThickness is not None:
                for i in range(self.numCrossSections):
                    yCS[i,:] -= self.voluteScrollRadius - y1p[i]
                    zCS[i,:] -= -z1p[i]
                    yShellCS[i,:] -= self.voluteScrollRadius - y1p[i]
                    zShellCS[i,:] -= -z1p[i]
                    if self.circlePrintability.lower() ==  'thick':
                        yInternalSupportWallCS[i,:]        -= self.voluteScrollRadius - y1p[i]
                        zInternalSupportWallCS[i,:]        -= -z1p[i]
                        yInternalSupportFilletUpperCS[i,:] -= self.voluteScrollRadius - y1p[i]
                        zInternalSupportFilletUpperCS[i,:] -= -z1p[i]
                        yInternalSupportFilletLowerCS[i,:] -= self.voluteScrollRadius - y1p[i]
                        zInternalSupportFilletLowerCS[i,:] -= -z1p[i]
                    if self.circlePrintability.lower() ==  'thin':
                        yInternalSupportWallCS[i,:]        -= self.voluteScrollRadius - y1p[i]
                        zInternalSupportWallCS[i,:]        -= -z1p[i]
                        yInternalSupportFilletUpperCS[i,:] -= self.voluteScrollRadius - y1p[i]
                        zInternalSupportFilletUpperCS[i,:] -= -z1p[i]
        else:
            raise Exception('Invalid wall alignment argument. Please specify inner or outer.')

        # roll cross sections about scroll axis to create mesh
        sweep = 2*np.pi - self.tongueGap()
        if self.scrollDirection.lower() == 'cw':
            rollAngle = np.linspace(0, sweep, self.numCrossSections)
        elif self.scrollDirection.lower() == 'ccw':
            rollAngle = np.linspace(sweep, 0, self.numCrossSections)
        else:
            raise Exception('Invalid scroll direction argument. Please specify cw or ccw.')
        xVolute, yVolute, zVolute = [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
        rollAboutAxis(rollAngle, (xCS, yCS, zCS),
                      (xVolute, yVolute, zVolute))

        # roll outer wall cross sections about scroll axis to create mesh
        if self.wallThickness is not None:
            xShell, yShell, zShell = [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
            rollAboutAxis(rollAngle, (xShellCS, yShellCS, zShellCS),
                          (xShell, yShell, zShell))

        # roll inner support cross sections about scroll axis to create mesh
        if self.circlePrintability.lower() == 'thick':
            xInternalSupportWall, yInternalSupportWall, zInternalSupportWall =                      \
                [np.zeros((self.numCrossSections,5)) for _ in range(3)]
            xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper = \
                [np.zeros((self.numCrossSections,int(1.5*self.crossSectionResolution+1))) for _ in range(3)]
            xInternalSupportFilletLower, yInternalSupportFilletLower, zInternalSupportFilletLower = \
                [np.zeros((self.numCrossSections,int(0.75*self.crossSectionResolution+2))) for _ in range(3)]
            rollAboutAxis(rollAngle, (xInternalSupportWallCS, yInternalSupportWallCS, zInternalSupportWallCS),
                          (xInternalSupportWall, yInternalSupportWall, zInternalSupportWall))
            rollAboutAxis(rollAngle, (xInternalSupportFilletUpperCS, yInternalSupportFilletUpperCS, zInternalSupportFilletUpperCS),
                          (xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper))
            rollAboutAxis(rollAngle, (xInternalSupportFilletLowerCS, yInternalSupportFilletLowerCS, zInternalSupportFilletLowerCS),
                          (xInternalSupportFilletLower, yInternalSupportFilletLower, zInternalSupportFilletLower))
        if self.circlePrintability.lower() == 'thin':
            xInternalSupportWall, yInternalSupportWall, zInternalSupportWall =                      \
                [np.zeros((self.numCrossSections,2)) for _ in range(3)]
            xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper = \
                [np.zeros((self.numCrossSections,self.crossSectionResolution)) for _ in range(3)]
            rollAboutAxis(rollAngle, (xInternalSupportWallCS, yInternalSupportWallCS, zInternalSupportWallCS),
                          (xInternalSupportWall, yInternalSupportWall, zInternalSupportWall))
            rollAboutAxis(rollAngle, (xInternalSupportFilletUpperCS, yInternalSupportFilletUpperCS, zInternalSupportFilletUpperCS),
                          (xInternalSupportFilletUpper, yInternalSupportFilletUpper, zInternalSupportFilletUpper))

        # axial location
        zVolute += self.axialOffset
        if self.wallThickness is not None:
            zShell += self.axialOffset
        if self.circlePrintability.lower() == 'thick':
            zInternalSupportWall        += self.axialOffset
            zInternalSupportFilletUpper += self.axialOffset
            zInternalSupportFilletLower += self.axialOffset
        if self.circlePrintability.lower() == 'thin':
            zInternalSupportWall        += self.axialOffset
            zInternalSupportFilletUpper += self.axialOffset

        # assign
        self.xVolute = xVolute
        self.yVolute = yVolute
        self.zVolute = zVolute
        if self.wallThickness is not None:
            self.xShell = xShell
            self.yShell = yShell
            self.zShell = zShell
        if self.circlePrintability.lower() == 'thick':
            self.xInternalSupportWall        = xInternalSupportWall
            self.yInternalSupportWall        = yInternalSupportWall
            self.zInternalSupportWall        = zInternalSupportWall
            self.xInternalSupportFilletUpper = xInternalSupportFilletUpper
            self.yInternalSupportFilletUpper = yInternalSupportFilletUpper
            self.zInternalSupportFilletUpper = zInternalSupportFilletUpper
            self.xInternalSupportFilletLower = xInternalSupportFilletLower
            self.yInternalSupportFilletLower = yInternalSupportFilletLower
            self.zInternalSupportFilletLower = zInternalSupportFilletLower
        if self.circlePrintability.lower() == 'thin':
            self.xInternalSupportWall        = xInternalSupportWall
            self.yInternalSupportWall        = yInternalSupportWall
            self.zInternalSupportWall        = zInternalSupportWall
            self.xInternalSupportFilletUpper = xInternalSupportFilletUpper
            self.yInternalSupportFilletUpper = yInternalSupportFilletUpper
            self.zInternalSupportFilletUpper = zInternalSupportFilletUpper
